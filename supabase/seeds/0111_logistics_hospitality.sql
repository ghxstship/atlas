-- 0111_logistics_hospitality.sql
-- A11 Logistics and Hospitality (Section 19.6: the demo tenant exercises the feature). On the demo
-- project NWS (Northwind Summer Series, Miami-Dade), every logistics and hospitality state is shown:
--   * a venue with two loading docks and a marshalling yard, linked to the project when it has none
--   * four shipments: one released through the whole flow (journey 20), one checked in at its dock,
--     one waiting at the gate, and one only logged, plus manifest lines and yard log entries
--   * lodging, catering, travel and amenity fulfillments in Active, Blocked and Proposed states, with
--     priced and unpriced lines, and a catering BEO generated by the Owner and approved by the Producer
--     (journey 21; separation of duties keeps the author from approving)
--   * flights and a ground transfer, and an accommodation block with room assignments
--
-- Changes run as the demo people through the same tables, triggers and RPCs the app uses, so display
-- keys, ledgers, domain events, the activity feed and the audit ledger carry real entries. Guarded on
-- A30's demo org and A07's demo project, and idempotent: nothing runs once the A11 venue exists.
--
-- Fixed ids this file adds (in A11's block 0111):
--   Demo venue Bayfront Pier                        01920000-0000-7000-8000-000000111001
--   Zones DOCK-A, DOCK-B, YARD-1                    01920000-0000-7000-8000-000000111011 to 111013

do $$
declare
  c_org constant uuid := '01920000-0000-7000-8000-000000000001';
  c_project constant uuid := '01920000-0000-7000-8000-000000001001';
  c_owner constant uuid := '01920000-0000-7000-8000-000000000101';
  c_producer constant uuid := '01920000-0000-7000-8000-000000000103';
  c_field constant uuid := '01920000-0000-7000-8000-000000000104';
  c_crew constant uuid := '01920000-0000-7000-8000-000000000201';
  c_venue constant uuid := '01920000-0000-7000-8000-000000111001';
  c_dock_a constant uuid := '01920000-0000-7000-8000-000000111011';
  c_dock_b constant uuid := '01920000-0000-7000-8000-000000111012';
  c_yard constant uuid := '01920000-0000-7000-8000-000000111013';
  v_carrier uuid;
  v_hotel uuid;
  v_caterer uuid;
  v_s1 uuid;
  v_s2 uuid;
  v_s3 uuid;
  v_s4 uuid;
  v_slot uuid;
  v_gate uuid;
  v_lodging uuid;
  v_catering uuid;
  v_travel uuid;
  v_amenity uuid;
  v_beo uuid;
  v_block uuid;
begin
  if not exists (select 1 from app.organizations where id = c_org)
     or not exists (select 1 from app.projects where id = c_project)
     or exists (select 1 from app.venues where id = c_venue) then
    return;
  end if;

  perform set_config('request.jwt.claims', json_build_object('sub', c_owner, 'role', 'authenticated')::text, true);

  -- Places for the docks and yard ---------------------------------------------------------------------------
  insert into app.venues (id, org_id, name, jurisdiction_id, time_zone)
  values (c_venue, c_org, 'Bayfront Pier', 'US-FL-MIAMI-DADE', 'America/New_York');
  insert into app.zones (id, venue_id, code, name) values
    (c_dock_a, c_venue, 'DOCK-A', 'Loading Dock A'),
    (c_dock_b, c_venue, 'DOCK-B', 'Loading Dock B'),
    (c_yard, c_venue, 'YARD-1', 'Marshalling Yard');
  update app.projects set venue_id = c_venue where id = c_project and venue_id is null;

  -- Suppliers -------------------------------------------------------------------------------------------------
  v_carrier := app.create_counterparty(c_org, 'Coastline Freight Lines', 'Logistics and Freight');
  v_hotel := app.create_counterparty(c_org, 'Harborview Hotel', 'Unclassified Vendor');
  v_caterer := app.create_counterparty(c_org, 'Tidewater Catering', 'Catering and Beverage');

  -- Shipments (journey 20) ------------------------------------------------------------------------------------
  insert into app.shipments (project_id, direction, carrier_counterparty_id, freight_type_enum_id, tracking_identifier, ships_at, arrives_at)
  values (c_project, 'Inbound', v_carrier, 'ENM-022', 'CFL-48213', '2027-03-08 14:00+00', '2027-03-09 13:00+00')
  returning id into v_s1;
  insert into app.shipment_lines (shipment_id, description, quantity) values
    (v_s1, 'Box Truss 12 in, 10 ft Sections', 24),
    (v_s1, 'Chain Motor, 1 Ton', 8),
    (v_s1, 'Stage Deck, 4 ft x 8 ft', 40);
  insert into app.dock_slots (project_id, zone_id, shipment_id, starts_at, ends_at)
  values (c_project, c_dock_a, v_s1, '2027-03-09 13:00+00', '2027-03-09 15:00+00') returning id into v_slot;
  insert into app.gate_queue (project_id, shipment_id, vehicle_identifier, arrived_at)
  values (c_project, v_s1, 'FL TRK-4821', '2027-03-09 12:40+00') returning id into v_gate;
  insert into app.marshalling_log (project_id, shipment_id, zone_id, entry, logged_at) values
    (c_project, v_s1, c_yard, 'Truck staged in lane 2, driver checked in with the yard marshal.', '2027-03-09 12:45+00');
  update app.dock_slots set checked_in_at = now() where id = v_slot;
  update app.gate_queue set released_at = now() where id = v_gate;
  insert into app.marshalling_log (project_id, shipment_id, zone_id, entry, logged_at) values
    (c_project, v_s1, c_dock_a, 'Released to Dock A; unload complete and seals recorded.', '2027-03-09 14:50+00');

  insert into app.shipments (project_id, direction, carrier_counterparty_id, freight_type_enum_id, tracking_identifier, arrives_at)
  values (c_project, 'Inbound', v_carrier, 'ENM-020', 'CFL-48377', '2027-03-10 14:00+00') returning id into v_s2;
  insert into app.shipment_lines (shipment_id, description, quantity) values
    (v_s2, 'Line Array Cabinet', 16),
    (v_s2, 'Amplifier Rack', 4);
  insert into app.dock_slots (project_id, zone_id, shipment_id, starts_at, ends_at)
  values (c_project, c_dock_b, v_s2, '2027-03-10 14:00+00', '2027-03-10 15:30+00') returning id into v_slot;
  update app.dock_slots set checked_in_at = now() where id = v_slot;

  insert into app.shipments (project_id, direction, freight_type_enum_id, arrives_at)
  values (c_project, 'Inbound', 'ENM-021', '2027-03-11 15:00+00') returning id into v_s3;
  insert into app.shipment_lines (shipment_id, description, quantity) values (v_s3, 'Radio Batteries, Case of 24', 6);
  insert into app.dock_slots (project_id, zone_id, shipment_id, starts_at, ends_at)
  values (c_project, c_dock_a, v_s3, '2027-03-11 15:00+00', '2027-03-11 15:30+00');
  insert into app.gate_queue (project_id, shipment_id, vehicle_identifier, arrived_at)
  values (c_project, v_s3, 'FL VAN-118', '2027-03-11 14:50+00');
  insert into app.marshalling_log (project_id, shipment_id, zone_id, entry, logged_at) values
    (c_project, v_s3, c_yard, 'Courier van holding at the gate for the Dock A window.', '2027-03-11 14:52+00');

  insert into app.shipments (project_id, direction, carrier_counterparty_id, freight_type_enum_id, ships_at)
  values (c_project, 'Outbound', v_carrier, 'ENM-022', '2027-03-16 13:00+00') returning id into v_s4;
  insert into app.shipment_lines (shipment_id, description, quantity) values (v_s4, 'Return of Truss and Motors', 1);

  -- Hospitality (journey 21) -------------------------------------------------------------------------------
  insert into app.fulfillments (project_id, fulfillment_kind, counterparty_id, title, starts_at, ends_at)
  values (c_project, 'Lodging', v_hotel, 'Crew Lodging at Harborview', '2027-03-10 20:00+00', '2027-03-16 15:00+00')
  returning id into v_lodging;
  insert into app.fulfillment_lines (fulfillment_id, description, person_id, quantity, unit_price_minor, currency_code) values
    (v_lodging, 'King Room, Six Nights', c_field, 6, 18900, 'USD'),
    (v_lodging, 'King Room, Six Nights', c_producer, 6, 18900, 'USD'),
    (v_lodging, 'Late Checkout', c_producer, 1, null, null);
  perform app.transition_fulfillment(v_lodging, 'Proposed', 'Active', 'Hotel confirmed the room list.');

  insert into app.fulfillments (project_id, fulfillment_kind, counterparty_id, title, starts_at, ends_at)
  values (c_project, 'Catering', v_caterer, 'Opening Night Crew Meal', '2027-03-13 21:00+00', '2027-03-13 23:00+00')
  returning id into v_catering;
  insert into app.fulfillment_lines (fulfillment_id, description, quantity, unit_price_minor, currency_code) values
    (v_catering, 'Hot Buffet, per Guest', 120, 2850, 'USD');
  insert into app.beos (project_id, fulfillment_id, event_at, guest_count)
  values (c_project, v_catering, '2027-03-13 21:30+00', 120) returning id into v_beo;
  insert into app.beo_lines (beo_id, description, quantity, unit_price_minor, currency_code) values
    (v_beo, 'Grilled Chicken and Vegetable Buffet', 120, 2400, 'USD'),
    (v_beo, 'Vegan Station', 20, 2200, 'USD'),
    (v_beo, 'Coffee and Water Service', 1, null, null);
  perform app.transition_fulfillment(v_catering, 'Proposed', 'Active', 'Menu agreed with the caterer.');

  insert into app.fulfillments (project_id, fulfillment_kind, title, starts_at)
  values (c_project, 'Travel', 'Crew Flights and Transfers', '2027-03-10 12:00+00') returning id into v_travel;
  insert into app.travel_segments (project_id, person_id, fulfillment_id, travel_mode, operator_name, service_identifier,
    confirmation_identifier, departs_from, departs_at, departs_time_zone, arrives_at_place, arrives_at, arrives_time_zone,
    price_minor, currency_code) values
    (c_project, c_field, v_travel, 'Flight', 'Coastal Air', 'CA 214', 'QX7P2L', 'BOS', '2027-03-10 12:00+00', 'America/New_York',
     'MIA', '2027-03-10 15:20+00', 'America/New_York', 31800, 'USD'),
    (c_project, c_field, v_travel, 'Ground', 'Bayside Car Service', null, null, 'MIA Arrivals, Door 6', '2027-03-10 15:50+00',
     'America/New_York', 'Harborview Hotel', '2027-03-10 16:30+00', 'America/New_York', null, null);
  perform app.transition_fulfillment(v_travel, 'Proposed', 'Active', 'Tickets issued.');
  perform app.transition_fulfillment(v_travel, 'Active', 'Blocked', 'Waiting on the return date for the crew lead.');

  insert into app.fulfillments (project_id, fulfillment_kind, title, starts_at)
  values (c_project, 'Amenity', 'Green Room Supplies', '2027-03-13 18:00+00') returning id into v_amenity;
  insert into app.fulfillment_lines (fulfillment_id, description, quantity) values (v_amenity, 'Fruit and Snack Tray', 4);

  insert into app.accommodation_blocks (project_id, counterparty_id, title, check_in_on, check_out_on, rooms_held, release_on,
    nightly_rate_minor, currency_code)
  values (c_project, v_hotel, 'Harborview Crew Block', date '2027-03-10', date '2027-03-16', 6, date '2027-02-24', 18900, 'USD')
  returning id into v_block;
  insert into app.accommodation_assignments (accommodation_block_id, person_id, check_in_on, check_out_on) values
    (v_block, c_field, date '2027-03-10', date '2027-03-16'),
    (v_block, c_producer, date '2027-03-10', date '2027-03-16'),
    (v_block, c_crew, date '2027-03-11', date '2027-03-15');

  -- The Producer approves the Owner's BEO: the author never approves their own (separation of duties).
  perform set_config('request.jwt.claims', json_build_object('sub', c_producer, 'role', 'authenticated')::text, true);
  update app.beos set approved_at = now() where id = v_beo;

  perform set_config('request.jwt.claims', '', true);
end;
$$;
