-- 0109_places_safety.sql
-- A09 Places and Safety demo data (Section 19.6: the demo tenant exercises the feature).
--
-- For the demo org and its demo project NWS (Northwind Summer Series, Miami-Dade):
--   * three venues: two located on the Miami waterfront and one not yet located, so the map view
--     shows two pins and names the third as unlocated
--   * spaces with canon URID types, zones for the access grid and radio plan, and a geofence
--   * capability documents: one frozen and current, one current and editable, one stale (gate 3)
--   * a site plan of the pier with pins on zones
--   * requirements and capabilities with a reconciliation run that leaves one gate 3 gap
--   * permit requirements generated by the canon permit engine, two tracked by Permit records
--   * two inspection templates and two inspections: one with a failure (its punch item opened) and
--     signed off by another person, one still in progress
--
-- Writes that have an RPC go through it, acting as the demo people, so ledgers, domain events,
-- activity and audit carry real entries. Guarded on A30's demo org and A07's demo project, and
-- idempotent: nothing runs when the first venue below already exists.

do $$
declare
  c_org constant uuid := '01920000-0000-7000-8000-000000000001';
  c_project constant uuid := '01920000-0000-7000-8000-000000001001';
  c_owner constant uuid := '01920000-0000-7000-8000-000000000101';
  c_producer constant uuid := '01920000-0000-7000-8000-000000000103';
  c_pier constant uuid := '01920000-0000-7000-8000-000000010901';
  c_park constant uuid := '01920000-0000-7000-8000-000000010902';
  c_hall constant uuid := '01920000-0000-7000-8000-000000010903';
  c_deck constant uuid := '01920000-0000-7000-8000-000000010911';
  c_compound constant uuid := '01920000-0000-7000-8000-000000010912';
  c_lawn constant uuid := '01920000-0000-7000-8000-000000010913';
  c_foh constant uuid := '01920000-0000-7000-8000-000000010921';
  c_boh constant uuid := '01920000-0000-7000-8000-000000010922';
  c_dock constant uuid := '01920000-0000-7000-8000-000000010923';
  c_gate constant uuid := '01920000-0000-7000-8000-000000010924';
  c_plan constant uuid := '01920000-0000-7000-8000-000000010931';
  c_walk constant uuid := '01920000-0000-7000-8000-000000010941';
  c_barrier constant uuid := '01920000-0000-7000-8000-000000010942';
  c_failed text := (select e.record_id from xpms.std_enumeration e where e.enum_domain = 'Inspection Result' and e.enum_code = 'INSP_FAILED');
  c_passed text := (select e.record_id from xpms.std_enumeration e where e.enum_domain = 'Inspection Result' and e.enum_code = 'INSP_PASSED');
  v_item uuid;
  v_inspection uuid;
  v_requirement uuid;
  v_record uuid;
begin
  if not exists (select 1 from app.organizations where id = c_org)
     or not exists (select 1 from app.projects where id = c_project)
     or exists (select 1 from app.venues where id = c_pier) then
    return;
  end if;

  -- The Owner sets up the org's places.
  perform set_config('request.jwt.claims', json_build_object('sub', c_owner, 'role', 'authenticated')::text, true);

  insert into app.venues (id, org_id, name, jurisdiction_id, time_zone, street_address, locality, postal_code) values
    (c_pier, c_org, 'Bayfront Pier Stage', 'US-FL-MIAMI-DADE', 'America/New_York', '301 Bayfront Walk', 'Miami', '33132'),
    (c_park, c_org, 'Harborside Park Lawn', 'US-FL-MIAMI-DADE', 'America/New_York', '1075 Harbor Drive', 'Miami', '33132'),
    (c_hall, c_org, 'Coral Assembly Hall', 'US-FL-MIAMI-DADE', 'America/New_York', null, 'Miami', null);
  perform app.set_venue_location(c_pier, -80.1855, 25.7752);
  perform app.set_venue_location(c_park, -80.1870, 25.7790);
  update app.projects set venue_id = c_pier where id = c_project and venue_id is null;

  insert into app.spaces (id, org_id, venue_id, urid, name, area_sq_ft, capacity) values
    (c_deck, c_org, c_pier, '5000.04.01', 'Pier Deck', 14000, 1800),
    (c_compound, c_org, c_pier, null, 'Backstage Compound', null, null),
    (c_lawn, c_org, c_park, null, 'Great Lawn', 52000, 3000);

  insert into app.zones (id, org_id, venue_id, space_id, code, name) values
    (c_foh, c_org, c_pier, c_deck, 'FOH', 'Front of House'),
    (c_boh, c_org, c_pier, c_compound, 'BOH', 'Backstage'),
    (c_dock, c_org, c_pier, null, 'DOCK-1', 'Loading Dock'),
    (c_gate, c_org, c_park, c_lawn, 'GATE-A', 'Main Gate');

  perform app.save_geofence(null, c_pier, null, 'Pier Site',
    '{"type":"Polygon","coordinates":[[[-80.1868,25.7744],[-80.1842,25.7744],[-80.1842,25.7760],[-80.1868,25.7760],[-80.1868,25.7744]]]}'::jsonb);

  insert into app.capability_documents (org_id, venue_id, title, document_uri, valid_from, valid_to, is_frozen) values
    (c_org, c_pier, 'Pier Tech Pack 2027', 'https://docs.example.com/bayfront/tech-pack-2027.pdf', date '2026-01-01', date '2027-12-31', true),
    (c_org, c_pier, 'Pier Tech Pack 2025', 'https://docs.example.com/bayfront/tech-pack-2025.pdf', date '2025-01-01', date '2025-12-31', false),
    (c_org, c_park, 'Park Rigging Plot', 'https://docs.example.com/harborside/rigging-plot.pdf', date '2026-06-01', null, false);

  insert into app.site_plans (id, org_id, project_id, venue_id, title, image_uri)
  values (c_plan, c_org, c_project, c_pier, 'Pier Ground Plan', 'plans/nws-pier-ground.png');
  insert into app.site_plan_pins (org_id, site_plan_id, label, x_ratio, y_ratio, zone_id) values
    (c_org, c_plan, 'FOH Mix', 0.50, 0.62, c_foh),
    (c_org, c_plan, 'First Aid', 0.15, 0.80, null),
    (c_org, c_plan, 'Dock Gate', 0.90, 0.30, c_dock);

  -- The Producer states what the show needs and what the pier provides, then reconciles.
  perform set_config('request.jwt.claims', json_build_object('sub', c_producer, 'role', 'authenticated')::text, true);
  insert into app.capability_statements (org_id, project_id, direction, urid, description, quantity, is_critical, assertion_word, venue_id) values
    (c_org, c_project, 'Require', '5000.06.01', 'Three-phase 400 A power at stage left.', 1, true, 'UNKNOWN', null),
    (c_org, c_project, 'Require', '5000.04.02', 'Stage decks for a 40 ft x 32 ft stage.', 1280, true, 'UNKNOWN', null),
    (c_org, c_project, 'Require', '6000.04.01', 'Controlled access at every gate.', null, false, 'UNKNOWN', null),
    (c_org, c_project, 'Provide', '5000.04.02', 'Pier deck staging, 1,400 sq ft of decks.', 1400, false, 'DOCUMENTED', c_pier),
    (c_org, c_project, 'Provide', '5000.06.01', 'House power, capacity not confirmed.', null, false, 'UNKNOWN', c_pier);
  perform app.reconcile_project(c_project, 'Pier walk with the venue technical director.');

  -- The permit engine reads the canon rules of Miami-Dade, Florida and the United States.
  perform app.generate_permit_requirements(c_project);
  select r.id into v_requirement from app.permit_requirements r where r.project_id = c_project and r.permit_rule = 'Special event';
  if v_requirement is not null then
    v_record := app.track_permit_requirement(v_requirement);
    perform app.transition_record(v_record, 'Proposed', 'Scheduled', 'Application filed with the Special Events Office.');
    update app.record_permit set permit_identifier = 'SE-2027-0142' where record_id = v_record;
  end if;
  select r.id into v_requirement from app.permit_requirements r where r.project_id = c_project and r.permit_rule = 'Amplified sound';
  if v_requirement is not null then
    perform app.track_permit_requirement(v_requirement);
  end if;

  -- Inspection templates (the Owner) and inspections (the Producer inspects, the Owner signs off).
  perform set_config('request.jwt.claims', json_build_object('sub', c_owner, 'role', 'authenticated')::text, true);
  insert into app.inspection_templates (id, org_id, name) values
    (c_walk, c_org, 'Daily Stage Walk'),
    (c_barrier, c_org, 'Crowd Barrier Check');
  insert into app.inspection_items (org_id, inspection_template_id, position, prompt, is_critical) values
    (c_org, c_walk, 1, 'Deck edges guarded on every open side', true),
    (c_org, c_walk, 2, 'Exits clear and lit', true),
    (c_org, c_walk, 3, 'Cable runs ramped or flown', false),
    (c_org, c_barrier, 1, 'Barrier sections pinned', true),
    (c_org, c_barrier, 2, 'Pit access gates latch', false);

  perform set_config('request.jwt.claims', json_build_object('sub', c_producer, 'role', 'authenticated')::text, true);
  v_inspection := app.start_inspection(c_project, c_walk, timestamptz '2027-03-11 15:00-04');
  for v_item in select it.id from app.inspection_items it where it.inspection_template_id = c_walk order by it.position loop
    perform app.record_inspection_result(v_inspection, v_item,
      case when (select it.position from app.inspection_items it where it.id = v_item) = 3 then c_failed else c_passed end,
      case when (select it.position from app.inspection_items it where it.id = v_item) = 3 then 'Cable run across the stage left stairs is not ramped.' else null end,
      null);
  end loop;
  perform set_config('request.jwt.claims', json_build_object('sub', c_owner, 'role', 'authenticated')::text, true);
  perform app.sign_off_inspection(v_inspection);

  perform set_config('request.jwt.claims', json_build_object('sub', c_producer, 'role', 'authenticated')::text, true);
  v_inspection := app.start_inspection(c_project, c_barrier, timestamptz '2027-03-12 16:30-04');
  select it.id into v_item from app.inspection_items it where it.inspection_template_id = c_barrier and it.position = 1;
  perform app.record_inspection_result(v_inspection, v_item, c_passed, null, null);

  perform set_config('request.jwt.claims', '', true);
end;
$$;
