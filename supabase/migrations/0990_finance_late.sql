-- Comments and attachments ------------------------------------------------------------------------------

insert into private.comment_subjects (table_name)
select t from unnest(array[
  'app.budgets', 'app.budget_lines', 'app.payments', 'app.journal_entries', 'app.accounting_periods', 'app.cost_centers'
]) t
where to_regclass(t) is not null
  and not exists (select 1 from private.comment_subjects s where s.table_name = t);

