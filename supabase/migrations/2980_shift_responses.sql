-- A "Still coming?" that ended elsewhere leaves the Inbox ----------------------------------------------------------------------------

create or replace function private.retire_shift_reconfirm_notices(p_shift_id uuid, p_person_id uuid)
returns void
language sql
volatile
security definer
set search_path = ''
as $$
  update app.notifications set archived_at = now()
  where subject_table = 'app.shifts' and subject_id = p_shift_id and kind = 'shift.reconfirm'
    and recipient_person_id = p_person_id and archived_at is null and deleted_at is null;
$$;

comment on function private.retire_shift_reconfirm_notices(uuid, uuid) is 'Archives a person''s live shift.reconfirm notifications about a shift once the ask has ended (answered, No Answer or Withdrawn), so a stale "Still coming?" does not fall into Gateway For Your Information or the Atlas Inbox and its email link reads as used.';
revoke all on function private.retire_shift_reconfirm_notices(uuid, uuid) from public, anon, authenticated;

-- Offers follow the shift's lifecycle ----------------------------------------------------------------------------------------------

create or replace function private.track_shift_offer()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_new_person uuid := case when new.deleted_at is null
    then private.shift_worker_person_id(new.membership_id, new.engagement_id, new.roster_entry_id) end;
  v_old_person uuid;
  v_worker_changed boolean := tg_op = 'INSERT';
  v_live boolean := new.deleted_at is null and new.shift_state <> 'Canceled';
  v_trusted boolean := private.in_trusted_operation('roster_shift_assignment')
    or private.in_trusted_operation('shift_reconfirm') or private.in_trusted_operation('position_fill');
begin
  if tg_op = 'UPDATE' then
    v_old_person := private.shift_worker_person_id(old.membership_id, old.engagement_id, old.roster_entry_id);
    v_worker_changed := (new.membership_id, new.engagement_id, new.roster_entry_id)
      is distinct from (old.membership_id, old.engagement_id, old.roster_entry_id);
    -- The previous person's "Still coming?" no longer applies once the shift moves to someone else, is canceled, removed
    -- or steps off Accepted, so a Waiting ask only ever sits on an Accepted shift. The three trusted operations step off
    -- Accepted before a worker change, which withdraws it here a moment later; a reopen answered it first.
    if v_old_person is not null
       and (v_worker_changed or not v_live or (old.shift_state = 'Accepted' and new.shift_state <> 'Accepted' and not v_trusted)) then
      update app.shift_responses r set answer = 'Withdrawn', answered_at = now()
      where r.shift_id = new.id and r.ask_kind = 'Reconfirmation' and r.answer = 'Waiting' and r.deleted_at is null
        and r.person_id = v_old_person;
      perform private.retire_shift_reconfirm_notices(new.id, v_old_person);
    end if;
    -- An RPC that reopens or moves an Accepted shift steps it back to Published first, keeping the worker for a moment:
    -- that step asks nobody. The worker change that follows in the same RPC does.
    if v_trusted and not v_worker_changed and old.shift_state = 'Accepted' and new.shift_state = 'Published' then
      return null;
    end if;
  end if;

  if new.shift_state = 'Published' and new.deleted_at is null and v_new_person is not null
     and not private.in_trusted_operation('shift_claim')
     and (tg_op = 'INSERT' or old.shift_state <> 'Published' or v_worker_changed or old.deleted_at is not null) then
    -- (a) Published to a person: any earlier Waiting Offer gives way to an ask of the person who holds it now.
    update app.shift_responses r set answer = 'Withdrawn', answered_at = now()
    where r.shift_id = new.id and r.ask_kind = 'Offer' and r.answer = 'Waiting' and r.deleted_at is null;
    insert into app.shift_responses (project_id, shift_id, person_id, ask_kind)
    values (new.project_id, new.id, v_new_person, 'Offer');
  elsif tg_op = 'UPDATE' and old.shift_state = 'Published' and new.shift_state = 'Accepted' and not v_worker_changed then
    -- (b) Accepted by the person asked.
    update app.shift_responses r set answer = 'Accepted', answered_at = now()
    where r.shift_id = new.id and r.ask_kind = 'Offer' and r.answer = 'Waiting' and r.deleted_at is null
      and r.person_id = v_new_person;
  elsif tg_op = 'UPDATE' and old.shift_state = 'Published'
        and (new.shift_state in ('Draft', 'Canceled') or new.deleted_at is not null or v_new_person is null
             or v_worker_changed) then
    -- (c) Back to Draft, canceled, removed or no longer anyone's: a Waiting Offer is withdrawn. app.decline_shift answers
    -- it Declined before its transition, so a declined offer is never Waiting here.
    update app.shift_responses r set answer = 'Withdrawn', answered_at = now()
    where r.shift_id = new.id and r.ask_kind = 'Offer' and r.answer = 'Waiting' and r.deleted_at is null;
  end if;
  return null;
end;
$$;

comment on function private.track_shift_offer() is 'After a shift''s state, worker or deletion changes (ADR 0148): a shift Published to a worker person asks them (a Waiting Offer, any earlier Waiting Offer withdrawn), unless a claim placed them (trusted operation shift_claim); Published to Accepted answers it Accepted; Published to Draft or Canceled, a soft delete or a cleared worker withdraws it. Any worker change, cancel, soft delete or step off Accepted outside the three trusted operations also withdraws the previous person''s Waiting Reconfirmation and retires its notification. Inside roster_shift_assignment, shift_reconfirm and position_fill an Accepted to Published step with the same worker asks nobody; the worker change that follows does. An agency slot names nobody and asks nobody.';
revoke all on function private.track_shift_offer() from public, anon, authenticated;

create trigger t93_track_shift_offer after insert or update of shift_state, membership_id, engagement_id, roster_entry_id, deleted_at
  on app.shifts for each row execute function private.track_shift_offer();

-- Shifts already Published to a person when this ships are asked from now, so the invariant holds from the first row.
insert into app.shift_responses (project_id, shift_id, person_id, ask_kind, asked_at)
select s.project_id, s.id, private.shift_worker_person_id(s.membership_id, s.engagement_id, s.roster_entry_id), 'Offer', now()
from app.shifts s
where s.deleted_at is null and s.shift_state = 'Published'
  and private.shift_worker_person_id(s.membership_id, s.engagement_id, s.roster_entry_id) is not null;

-- An answer is never deleted by hand, so nothing here enters Trash; the registry stays exact (ADR 0110).
select private.sync_trash_tables();
