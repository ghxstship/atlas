-- Table --------------------------------------------------------------------------------------------------------------------------

create table app.shift_responses (
  id uuid primary key default private.uuid_v7(),
  org_id uuid not null references app.organizations (id),
  project_id uuid not null references app.projects (id),
  shift_id uuid not null references app.shifts (id),
  person_id uuid not null references app.people (id),
  ask_kind app.shift_ask_kind not null,
  answer app.shift_answer not null default 'Waiting',
  asked_at timestamptz not null default now(),
  answered_at timestamptz,
  reason text,
  constraint shift_responses_answered check ((answer = 'Waiting') = (answered_at is null)),
  constraint shift_responses_reason_length check (reason is null or char_length(btrim(reason)) between 1 and 500)
);

