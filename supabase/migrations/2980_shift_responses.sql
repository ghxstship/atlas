-- 2980_shift_responses.sql
-- B9 Crew scheduling policy, positions and coverage (RRR-233; ADR 0148 decision 2; parity gaps G-123 and G-131).
-- Offers and reconfirmations are one fact table: each row of app.shift_responses is one ask of one person about one
-- shift, and its answer. It is the single source of the "Still coming?" flow (2981), the shortages page (2986) and the
-- invitation responses report (2987).
--
--   * Offer rows are written by the database from the shift's lifecycle (t93_track_shift_offer), never by a caller:
--     a shift Published to a person asks them (Waiting); accepting answers Accepted; app.decline_shift answers
--     Declined with the reason (2981); a reassignment, a return to Draft, a cancel, a soft delete or a cleared worker
--     withdraws a Waiting ask. A claim (1322, trusted operation shift_claim) and an agency slot with no person write
--     nothing. Inside roster_shift_assignment, shift_reconfirm and position_fill, the Accepted to Published step that
--     comes before a worker change writes nothing: the worker change that follows does.
--   * Any worker change, a cancel, a soft delete or a step off Accepted outside those three operations also withdraws
--     the previous person's Waiting Reconfirmation and retires its notification (private.retire_shift_reconfirm_notices).
--   * Two invariants: a live shift has a Waiting Offer exactly when it is Published with a worker person (a claim reaches
--     Accepted in the transaction that placed the person, so it is never seen that way), and a Waiting Reconfirmation
--     exists only on an Accepted shift.
--   * The seven Scheduling settings of B9 are defined here (generated from packages/schemas/settings/b9.yaml); 2981 to
--     2983 read them.

