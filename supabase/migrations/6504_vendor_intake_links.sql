-- 6504_vendor_intake_links.sql
-- B2 (RRR-226, ADR 0141; parity gap G-226, the link side). A reusable vendor intake link: one link and access code a
-- project hands to many vendors or contractors, each of whom signs in to Gateway, gives the company account, a tax
-- form, a payout reference, a typed signature on the pinned agreement and an optional first invoice, and sends a
-- request the team approves into an Onboarding engagement (6505). Before this an engagement started only from an
-- accepted application (0775) or a member's own entry.
--   * app.vendor_intake_links carries the engagement terms of the role (role, classification, pay basis and
--     arrangement as one canon rate card row, and the dates), a counterparty type for vendors, the optional agreement
--     pinned to its latest version at creation, what the intake collects, an expiry within 90 days, a cap on requests
--     (1 to 500) and the hashes of the xvin_ token and its 6-digit code (Section 7.5 invariant 8). An intake link never
--     engages an employee, so XOS-ENG-2 and XOS-ENG-3 cannot apply (vendor_intake_classification).
--   * The agreement must be a file uploaded in Knowledge (a document version with a clean attachment version) and
--     Public or Internal; the public page downloads exactly that version by ticket and never shows its body.
--   * api_public.open_vendor_intake checks the token and code as open_live_link does (read-only call refused first,
--     vendor_intake.failure 20 per relayed address in 10 minutes and vendor_intake.hop_failure 2000 per reaching
--     address in 15, the row locked before the compare, 5 wrong codes lock the link) and answers a 24-hour grant
--     (xvig_). A link that has reached its cap answers intake_link_full. A locked link is regenerated by the team;
--     ADR 0141 records that one stranger can lock a reusable link for every vendor with 5 wrong codes.
--   * api_public.vendor_intake answers the brand's Public columns, the project's name, the title, instructions, role
--     type and title, dates, what is collected and the agreement's title and version; never the note or the rate.
--   * Download tickets gain the intake link as their fourth source, and app.consume_file_download_ticket (latest 6502)
--     answers nothing once the link is revoked or expired or the file is raised above Internal.
-- No stored count: the requests are counted under the link's row lock (6505).

