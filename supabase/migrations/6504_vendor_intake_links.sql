create or replace function app.regenerate_vendor_intake_link(p_id uuid)
returns table (token text, access_code text, expires_at timestamptz)
language plpgsql
volatile
security definer
set search_path = ''
as $$
#variable_conflict use_column
declare
  v_link app.vendor_intake_links := private.manageable_vendor_intake_link(p_id);
  v_token text := 'xvin_' || encode(extensions.gen_random_bytes(32), 'hex');
  v_code text := private.new_live_link_code();
begin
  if v_link.revoked_at is not null then
    perform private.refuse('vendor_intake_link_revoked', 'A revoked intake link stays revoked. Make a new link instead.');
  end if;
  if private.org_read_only(v_link.org_id) then
    perform private.refuse('org_read_only', 'This organization is canceled and read-only. The Owner can reactivate it in Settings, Danger zone, during the 30 days.');
  end if;
  insert into private.retired_vendor_intake_tokens (token_hash) values (v_link.token_hash) on conflict do nothing;
  perform private.begin_trusted_operation('vendor_intake_service');
  update app.vendor_intake_links
  set token_hash = private.share_token_hash(v_token), token_hint = right(v_token, 4),
    access_code_hash = private.share_code_hash(v_token, v_code), failed_attempts = 0, rotated_at = now()
