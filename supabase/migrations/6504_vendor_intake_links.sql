-- Checks a token and its grant for the read and submit RPCs; answers the link or the reason.
create or replace function private.vendor_intake_reader(
  p_token text,
  p_grant text,
  p_client_address text,
  out o_link app.vendor_intake_links,
  out o_reason text
)
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_subjects record;
  v_hash bytea;
  v_grant_hash bytea;
  v_granted boolean;
begin
  perform private.require_read_write();
  select * into v_subjects from private.live_link_subjects(p_client_address);
  if p_token is not null and p_token ~ '^xvin_[0-9a-f]{64}$' then
    v_hash := private.share_token_hash(p_token);
    select * into o_link from app.vendor_intake_links l where l.token_hash = v_hash;
  end if;
  v_grant_hash := case when p_grant ~ '^xvig_[0-9a-f]{64}$' then private.share_token_hash(p_grant) end;
  v_granted := o_link.id is not null and v_grant_hash is not null and exists (
    select 1 from private.vendor_intake_grants g
    where g.grant_hash = v_grant_hash and g.vendor_intake_link_id = o_link.id and g.expires_at > now());
  if not v_granted and private.vendor_intake_rate_limited(v_subjects.o_hop, v_subjects.o_subject) then
    o_reason := 'intake_link_rate_limited';
    return;
  end if;
  if o_link.id is null then
    if v_hash is null or not exists (select 1 from private.retired_vendor_intake_tokens r where r.token_hash = v_hash) then
      perform private.note_vendor_intake_failure(v_subjects.o_hop, v_subjects.o_subject);
    end if;
    o_reason := 'intake_link_invalid';
    return;
  end if;
  if o_link.revoked_at is not null or o_link.deleted_at is not null then
    o_reason := 'intake_link_invalid';
  elsif o_link.expires_at <= now() then
    o_reason := 'intake_link_expired';
  elsif not v_granted then
    o_reason := 'intake_grant';
  elsif private.rate_limit_exceeded('vendor_intake.fetch', encode(v_grant_hash, 'hex'), 600, interval '1 hour') then
    o_reason := 'intake_link_rate_limited';
  end if;
  if o_reason is null then
    perform private.note_rate_event('vendor_intake.fetch', encode(v_grant_hash, 'hex'));
  end if;
end;
$$;

comment on function private.vendor_intake_reader(text, text, text) is 'Checks a vendor intake read or submit: refuses a read-only transaction first, then the address failure limits (only without a valid grant), the token (intake_link_invalid, intake_link_expired), the grant (intake_grant) and 600 reads an hour per grant (intake_link_rate_limited). Answers the link or the reason.';
revoke all on function private.vendor_intake_reader(text, text, text) from public, anon, authenticated;

