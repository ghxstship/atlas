create or replace function api_public.open_vendor_intake(p_token text, p_access_code text default null, p_client_address text default null)
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_subjects record;
  v_hash bytea;
  v_link app.vendor_intake_links;
  v_grant text;
  v_grant_expires timestamptz;
begin
  perform private.require_read_write();
  select * into v_subjects from private.live_link_subjects(p_client_address);
  if private.vendor_intake_rate_limited(v_subjects.o_hop, v_subjects.o_subject) then
    return private.live_link_refusal('intake_link_rate_limited');
  end if;
  if p_token is not null and p_token ~ '^xvin_[0-9a-f]{64}$' then
    v_hash := private.share_token_hash(p_token);
    select * into v_link from app.vendor_intake_links l where l.token_hash = v_hash for update;
  end if;
  if v_link.id is null then
    if v_hash is null or not exists (select 1 from private.retired_vendor_intake_tokens r where r.token_hash = v_hash) then
      perform private.note_vendor_intake_failure(v_subjects.o_hop, v_subjects.o_subject);
    end if;
    return private.live_link_refusal('intake_link_invalid');
  end if;
  if v_link.revoked_at is not null or v_link.deleted_at is not null then
    return private.live_link_refusal('intake_link_invalid');
  end if;
  if v_link.failed_attempts >= 5 then
    perform private.note_vendor_intake_failure(v_subjects.o_hop, v_subjects.o_subject);
    return private.live_link_refusal('intake_link_locked');
  end if;
  if v_link.expires_at <= now() then
    return private.live_link_refusal('intake_link_expired');
  end if;
  if private.org_read_only(v_link.org_id) then
    return private.live_link_refusal('org_read_only');
  end if;
  if private.vendor_intake_request_count(v_link.id) >= v_link.max_requests then
    return private.live_link_refusal('intake_link_full');
  end if;
  if nullif(btrim(coalesce(p_access_code, '')), '') is null then
    return private.live_link_refusal('intake_access_code_required');
  end if;
  if v_link.access_code_hash <> private.share_code_hash(p_token, p_access_code) then
    perform private.begin_trusted_operation('vendor_intake_service');
    update app.vendor_intake_links l set failed_attempts = least(l.failed_attempts + 1, 5) where l.id = v_link.id;
    perform private.end_trusted_operation('vendor_intake_service');
    perform private.note_vendor_intake_failure(v_subjects.o_hop, v_subjects.o_subject);
    return private.live_link_refusal(case when v_link.failed_attempts + 1 >= 5 then 'intake_link_locked' else 'intake_access_code' end);
  end if;

  delete from private.vendor_intake_grants g where g.expires_at < now() - interval '1 day';
  v_grant := 'xvig_' || encode(extensions.gen_random_bytes(32), 'hex');
  v_grant_expires := least(v_link.expires_at, now() + interval '24 hours');
  insert into private.vendor_intake_grants (grant_hash, org_id, vendor_intake_link_id, expires_at)
  values (private.share_token_hash(v_grant), v_link.org_id, v_link.id, v_grant_expires);
  return jsonb_build_object('status', 'ok', 'grant', v_grant, 'grant_expires_at', v_grant_expires);
end;
$$;

