create or replace function app.create_vendor_intake_link(
  p_project_id uuid,
  p_title text,
  p_role_type app.external_role_type,
  p_role_code text,
  p_worker_classification text,
  p_pay_basis text,
  p_arrangement text,
  p_start_date date,
  p_expires_at timestamptz,
  p_end_date date default null,
  p_counterparty_type text default null,
  p_agreement_document_id uuid default null,
  p_instructions text default null,
  p_note text default null,
  p_collect_tax_form boolean default true,
  p_collect_payout boolean default true,
  p_collect_invoice boolean default false,
  p_max_requests integer default 50
)
returns table (vendor_intake_link_id uuid, token text, access_code text, expires_at timestamptz)
language plpgsql
volatile
security definer
set search_path = ''
as $$
#variable_conflict use_column
declare
  v_project app.projects;
  v_document app.documents;
  v_version app.document_versions;
  v_file app.attachment_versions;
  v_token text := 'xvin_' || encode(extensions.gen_random_bytes(32), 'hex');
  v_code text := private.new_live_link_code();
  v_id uuid;
begin
  perform private.require_person();
  select * into v_project from app.projects p where p.id = p_project_id and p.deleted_at is null;
  if v_project.id is null or not private.is_member(v_project.org_id) then
    raise exception using errcode = '42501', message = 'project not found';
  end if;
  if not private.can_on_project(v_project.id, 'opportunities.engagement.write') then
    raise exception using errcode = '42501', message = 'opportunities.engagement.write is required on the project';
  end if;
  if private.org_read_only(v_project.org_id) then
    perform private.refuse('org_read_only', 'This organization is canceled and read-only. The Owner can reactivate it in Settings, Danger zone, during the 30 days.');
  end if;
  if p_role_type is null or p_role_type not in ('Vendor', 'Contractor') then
    perform private.refuse('vendor_intake_role_type', 'An intake link engages a Vendor or a Contractor.');
  end if;
  if p_role_type = 'Vendor' and p_counterparty_type is null then
    perform private.refuse('vendor_intake_counterparty_type', 'Choose the counterparty type new vendors get.');
  end if;
  if coalesce((select w.is_employee from xpms.worker_classification w where w.code = p_worker_classification), true) then
    perform private.refuse('vendor_intake_classification', 'An intake link engages vendors and contractors only; choose a classification that is not employment.');
  end if;
  if not exists (
    select 1 from xpms.rate_card r
    where r.role_code = p_role_code and r.worker_classification = p_worker_classification
      and r.pay_basis is not distinct from p_pay_basis and r.arrangement is not distinct from p_arrangement) then
    perform private.refuse('vendor_intake_rate_card', 'The role, classification, pay basis and arrangement must be one row of the rate card.');
  end if;
  if p_expires_at is null or p_expires_at <= now() or p_expires_at > now() + interval '90 days' then
    perform private.refuse('vendor_intake_expiry_range', 'An intake link expires after now and within 90 days.');
  end if;
  if p_agreement_document_id is not null then
    -- The caller must read the document under the documents policy (0353): knowledge.document.read in the org for an
    -- org document, or on the link's project for a project document.
    select * into v_document from app.documents d
    where d.id = p_agreement_document_id and d.deleted_at is null and d.org_id = v_project.org_id
      and ((d.project_id is null and private.has_capability(d.org_id, 'knowledge.document.read'))
        or (d.project_id = v_project.id and private.can_on_project(v_project.id, 'knowledge.document.read')));
    if v_document.id is null then
      raise exception using errcode = '42501', message = 'document not found';
    end if;
    select * into v_version from app.document_versions v
    where v.document_id = v_document.id order by v.version_number desc, v.id desc limit 1;
    v_file := private.vendor_intake_agreement_file(v_version.id);
    if v_version.id is null or v_file.id is null then
      perform private.refuse('intake_agreement_file', 'Upload the agreement as a file in Knowledge first.');
    end if;
    if (select a.classification from app.attachments a where a.id = v_file.attachment_id) not in ('Public', 'Internal') then
      perform private.refuse('intake_agreement_classified', 'Only a Public or Internal agreement can be shown through an intake link.');
    end if;
  end if;

  perform private.begin_trusted_operation('vendor_intake_service');
  insert into app.vendor_intake_links as l (project_id, role_type, role_code, worker_classification, pay_basis, arrangement,
    counterparty_type, start_date, end_date, agreement_document_id, agreement_version_id, title, instructions, note,
    collect_tax_form, collect_payout, collect_invoice, token_hash, token_hint, access_code_hash, expires_at, max_requests)
  values (v_project.id, p_role_type, p_role_code, p_worker_classification, p_pay_basis, p_arrangement,
    case when p_role_type = 'Vendor' then p_counterparty_type end, p_start_date, p_end_date, v_document.id, v_version.id,
    btrim(p_title), nullif(btrim(coalesce(p_instructions, '')), ''), nullif(btrim(coalesce(p_note, '')), ''),
    coalesce(p_collect_tax_form, true), coalesce(p_collect_payout, true), coalesce(p_collect_invoice, false),
    private.share_token_hash(v_token), right(v_token, 4), private.share_code_hash(v_token, v_code), p_expires_at,
    coalesce(p_max_requests, 50))
  returning l.id into v_id;
  perform private.end_trusted_operation('vendor_intake_service');
  perform private.emit_event(v_project.org_id, 'vendor_intake_link.created', 'vendor_intake_links', v_id, v_project.id,
    jsonb_build_object('role_type', p_role_type, 'expires_at', p_expires_at));
  return query select v_id, v_token, v_code, p_expires_at;
end;
$$;

