create or replace function private.guard_vendor_intake_link()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not private.in_trusted_operation('vendor_intake_service') then
    perform private.refuse('vendor_intake_link_immutable', 'A vendor intake link is made, opened, regenerated and revoked only through its RPCs.');
  end if;
  if coalesce((select w.is_employee from xpms.worker_classification w where w.code = new.worker_classification), true) then
    perform private.refuse('vendor_intake_classification', 'An intake link engages vendors and contractors only; choose a classification that is not employment.');
  end if;
  if tg_op = 'UPDATE' and (new.project_id <> old.project_id or new.role_type <> old.role_type or new.role_code <> old.role_code
     or new.worker_classification <> old.worker_classification or new.agreement_version_id is distinct from old.agreement_version_id) then
    perform private.refuse('vendor_intake_link_immutable', 'An intake link keeps its project, terms and agreement; make a new link instead.');
  end if;
  if tg_op = 'UPDATE' and old.revoked_at is not null and new.revoked_at is distinct from old.revoked_at then
    perform private.refuse('vendor_intake_link_revoked', 'A revoked intake link stays revoked. Make a new link instead.');
  end if;
  return new;
end;
$$;

comment on function private.guard_vendor_intake_link() is 'Vendor intake links: rows are inserted and changed only inside the intake RPCs (trusted operation vendor_intake_service); the worker classification is never an employee one (vendor_intake_classification, against xpms.worker_classification.is_employee); a link keeps its project, terms and agreement, and a revoked link stays revoked.';
revoke all on function private.guard_vendor_intake_link() from public, anon, authenticated;

create trigger t40_guard_vendor_intake_link before insert or update on app.vendor_intake_links
  for each row execute function private.guard_vendor_intake_link();

