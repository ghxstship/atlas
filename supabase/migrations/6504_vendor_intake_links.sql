-- The agreement's pinned version: its latest document version, when that version is a file uploaded in Knowledge (a
-- clean attachment version names it, as 0590's record_attachment_scan writes) and the file is Public or Internal.
create or replace function private.vendor_intake_agreement_file(p_version_id uuid)
returns app.attachment_versions
language sql
stable
security definer
set search_path = ''
as $$
  select v.* from app.attachment_versions v
  where v.document_version_id = p_version_id and v.scan_status = 'Clean' and v.deleted_at is null
  order by v.version_number desc, v.id desc
  limit 1;
$$;

