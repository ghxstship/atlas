-- 2251_member_availability.sql
--
-- Members' availability and the availability window (ADR 0022, 2250-2259), A132, RRR-194, ADR 0063. Section 4.5.6
-- item 25 lists availability among the Scheduling settings. Availability calendars (0740) were Gateway people's:
-- a person's own calendar, or one kept for one org's bookings (ADR 0019 item 10; person-owned rows, ADR 0033
-- decision 69). This migration extends the calendar kept for an org to the org's members:
--   * a member states their availability for the org on that calendar (app.ensure_member_availability_calendar finds
--     or opens it), and the org's planners (crew.shift.write on any of its projects) read it while the person holds an
--     active membership, whatever its visibility: a calendar kept for one org is that org's to see (0740). The owner's
--     notes stay theirs alone; planners read the period and kind;
--   * the org's rule (scheduling.availability_required, scheduling.availability_notice_days and
--     scheduling.availability_horizon_days): while availability is required, members state it for the next horizon
--     days, and a member's availability inside the notice period is locked (availability_inside_notice), so planners
--     can rely on it. app.my_availability_status tells the member which days in the window are still unstated;
--   * app.rank_shift_candidates ranks the org's members for one shift for the schedule's drag list: free of an
--     overlapping shift first, then by stated availability (Available, Tentative, not stated, Unavailable), then
--     those who worked the role before, then the fewest hours that week. A member who has not stated availability the
--     rule requires is marked overdue.

-- The org's availability rule -------------------------------------------------------------------------------------------

-- Statements generated by `pnpm --filter @xos/schemas settings:sql a132`.
select private.define_setting('scheduling.availability_required', 'Boolean', 'org.scheduling.write', array['organization'], false, p_default_boolean => false);
select private.define_setting('scheduling.availability_notice_days', 'Integer', 'org.scheduling.write', array['organization'], false, p_default_integer => 7, p_min_integer => 0, p_max_integer => 60);
select private.define_setting('scheduling.availability_horizon_days', 'Integer', 'org.scheduling.write', array['organization'], false, p_default_integer => 28, p_min_integer => 7, p_max_integer => 180);

create or replace function private.availability_rule(p_org_id uuid)
returns table (required boolean, notice_days integer, horizon_days integer)
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(private.org_boolean_setting(p_org_id, 'scheduling.availability_required'), false),
    coalesce(private.org_setting_integer(p_org_id, 'scheduling.availability_notice_days'), 7)::integer,
    coalesce(private.org_setting_integer(p_org_id, 'scheduling.availability_horizon_days'), 28)::integer;
$$;

comment on function private.availability_rule(uuid) is 'An org''s availability window (A132, ADR 0063): whether members must state their availability (scheduling.availability_required), the days ahead inside which it is locked (scheduling.availability_notice_days) and how many days ahead it must be stated (scheduling.availability_horizon_days).';
revoke all on function private.availability_rule(uuid) from public, anon, authenticated;

create or replace function private.is_active_member(p_person_id uuid, p_org_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from app.memberships m
    where m.person_id = p_person_id and m.org_id = p_org_id and m.deleted_at is null
      and m.valid_from <= now() and (m.valid_to is null or m.valid_to > now()));
$$;

comment on function private.is_active_member(uuid, uuid) is 'True while the person holds an active membership of the org.';
revoke all on function private.is_active_member(uuid, uuid) from public, anon, authenticated;

-- Who sees a calendar: 0740's rule, and the org's planners for a member's calendar kept for the org ---------------------

create or replace function private.availability_shared_with_me(p_person_id uuid, p_org_id uuid, p_visibility app.availability_visibility)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select p_person_id = private.current_person_id()
    or (p_org_id is null and p_visibility = 'Public' and private.current_person_id() is not null)
    or (p_visibility <> 'Private' and exists (
      select 1 from app.applications a join app.opportunities o on o.id = a.opportunity_id
      where a.applicant_person_id = p_person_id and a.deleted_at is null
        and (p_org_id is null or o.org_id = p_org_id)
        and o.project_id in (select private.project_ids_with('opportunities.application.read'))))
    or (p_visibility <> 'Private' and exists (
      select 1 from app.engagements e
      where e.person_id = p_person_id and e.deleted_at is null
        and e.engagement_state in ('Onboarding', 'Blocked', 'Active', 'Closing')
        and (p_org_id is null or e.org_id = p_org_id)
        and e.project_id in (select private.project_ids_with('opportunities.engagement.read'))))
    or (p_org_id is not null and private.is_active_member(p_person_id, p_org_id) and exists (
      select 1 from app.projects p
      where p.org_id = p_org_id and p.deleted_at is null
        and p.id in (select private.project_ids_with('crew.shift.write'))));
$$;

comment on function private.availability_shared_with_me(uuid, uuid, app.availability_visibility) is 'True when the signed-in person may see a calendar: its owner; anyone signed in for a Public general calendar; unless Private, members who read an application or an open engagement of the owner with their org; and, for a calendar kept for an org whose owner is an active member of it, the org''s planners (crew.shift.write on any of its projects, A132). Takes the calendar''s column values.';

revoke all on function private.availability_shared_with_me(uuid, uuid, app.availability_visibility) from public, anon;
grant execute on function private.availability_shared_with_me(uuid, uuid, app.availability_visibility) to authenticated, service_role;

-- A member's calendar for the org ---------------------------------------------------------------------------------------

create or replace function app.ensure_member_availability_calendar(p_org_id uuid, p_time_zone text default null)
returns uuid
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_person uuid := private.require_person();
  v_id uuid;
begin
  if not private.is_active_member(v_person, p_org_id) then
    raise exception using errcode = '42501', message = 'only a member states availability for an org';
  end if;
  select c.id into v_id from app.availability_calendars c
  where c.person_id = v_person and c.org_id = p_org_id and c.deleted_at is null;
  if v_id is null then
    insert into app.availability_calendars (org_id, person_id, time_zone)
    values (p_org_id, v_person,
      coalesce(nullif(btrim(p_time_zone), ''), private.org_setting_text(p_org_id, 'locale.time_zone'), 'UTC'))
    returning id into v_id;
  end if;
  return v_id;
end;
$$;

comment on function app.ensure_member_availability_calendar(uuid, text) is 'The signed-in member''s availability calendar kept for the org (A132), opened in the given IANA zone or the org''s when they have none. Members only.';

revoke all on function app.ensure_member_availability_calendar(uuid, text) from public, anon;
grant execute on function app.ensure_member_availability_calendar(uuid, text) to authenticated, service_role;

-- The notice lock --------------------------------------------------------------------------------------------------------

create or replace function private.guard_member_availability_block()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_calendar app.availability_calendars;
  v_rule record;
  v_cutoff timestamptz;
begin
  if auth.uid() is null then
    return new;
  end if;
  select * into v_calendar from app.availability_calendars c where c.id = new.availability_calendar_id;
  if v_calendar.org_id is null or not private.is_active_member(v_calendar.person_id, v_calendar.org_id) then
    return new;
  end if;
  select * into v_rule from private.availability_rule(v_calendar.org_id);
  if not v_rule.required or v_rule.notice_days = 0 then
    return new;
  end if;
  if tg_op = 'UPDATE' and new.starts_at = old.starts_at and new.ends_at = old.ends_at
     and new.availability_kind = old.availability_kind and new.deleted_at is not distinct from old.deleted_at then
    return new;
  end if;
  v_cutoff := now() + make_interval(days => v_rule.notice_days);
  if new.starts_at < v_cutoff or (tg_op = 'UPDATE' and old.starts_at < v_cutoff) then
    perform private.refuse('availability_inside_notice',
      format('Availability for the next %s days is locked; tell your planner if you cannot work a shift in that period.', v_rule.notice_days));
  end if;
  return new;
end;
$$;

comment on function private.guard_member_availability_block() is 'While the org requires availability (scheduling.availability_required), a member''s periods on their calendar for the org that start inside the notice period (scheduling.availability_notice_days) are locked against new, changed and removed periods (A132). Only the calendar''s owner writes its periods (0740), so nobody signed in can change a locked one; planners reassign the shift instead. Notes stay editable; the platform is not refused.';
revoke all on function private.guard_member_availability_block() from public, anon, authenticated;

create trigger t41_guard_member_availability before insert or update on app.availability_blocks
  for each row execute function private.guard_member_availability_block();

-- The member's window --------------------------------------------------------------------------------------------------

create or replace function app.my_availability_status(p_org_id uuid)
returns table (
  availability_calendar_id uuid,
  time_zone text,
  required boolean,
  notice_days integer,
  horizon_days integer,
  locked_until date,
  unstated_days date[]
)
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_person uuid := private.require_person();
  v_calendar app.availability_calendars;
  v_rule record;
  v_zone text;
  v_today date;
begin
  if not private.is_active_member(v_person, p_org_id) then
    raise exception using errcode = '42501', message = 'only a member reads their availability for an org';
  end if;
  select * into v_calendar from app.availability_calendars c
  where c.person_id = v_person and c.org_id = p_org_id and c.deleted_at is null;
  select * into v_rule from private.availability_rule(p_org_id);
  v_zone := coalesce(v_calendar.time_zone, private.org_setting_text(p_org_id, 'locale.time_zone'), 'UTC');
  v_today := (now() at time zone v_zone)::date;
  return query
  select v_calendar.id, v_zone, v_rule.required, v_rule.notice_days, v_rule.horizon_days,
    case when v_rule.required then v_today + v_rule.notice_days end,
    coalesce((
      select array_agg(d::date order by d)
      from generate_series(v_today + v_rule.notice_days, v_today + v_rule.horizon_days - 1, interval '1 day') d
      where not exists (
        select 1 from app.availability_blocks b
        where b.availability_calendar_id = v_calendar.id and b.deleted_at is null
          and b.starts_at < ((d::date + 1)::timestamp at time zone v_zone)
          and b.ends_at > (d::date::timestamp at time zone v_zone))), '{}');
end;
$$;

comment on function app.my_availability_status(uuid) is 'The signed-in member''s availability window for the org (A132): their calendar kept for it (null until opened) and its zone, the org''s rule (scheduling.availability_required, notice and horizon days), the first day they may still change while availability is required, and the days from the end of the notice period to the horizon with no period stated.';

revoke all on function app.my_availability_status(uuid) from public, anon;
grant execute on function app.my_availability_status(uuid) to authenticated, service_role;

-- Ranking crew for a shift ----------------------------------------------------------------------------------------------

create or replace function app.rank_shift_candidates(p_shift_id uuid, p_week_start date default null)
returns table (
  membership_id uuid,
  person_id uuid,
  full_name text,
  availability text,
  overdue boolean,
  conflict boolean,
  worked_role boolean,
  week_minutes integer,
  candidate_rank integer
)
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_shift app.shifts;
  v_rule record;
  v_week_start timestamptz;
begin
  perform private.require_person();
  select * into v_shift from app.shifts s where s.id = p_shift_id and s.deleted_at is null;
  if v_shift.id is null or not private.can_on_project(v_shift.project_id, 'crew.shift.write') then
    raise exception using errcode = '42501', message = 'crew.shift.write is required on the shift''s project';
  end if;
  select * into v_rule from private.availability_rule(v_shift.org_id);
  v_week_start := coalesce(p_week_start, date_trunc('week', v_shift.starts_at at time zone v_shift.time_zone)::date)::timestamp
    at time zone v_shift.time_zone;
  return query
  with members as (
    select m.id as membership_id, m.person_id, p.full_name
    from app.memberships m join app.people p on p.id = m.person_id
    where m.org_id = v_shift.org_id and m.deleted_at is null and p.deleted_at is null
      and m.valid_from <= now() and (m.valid_to is null or m.valid_to > now())
      and m.id is distinct from v_shift.membership_id
  ), blocks as (
    select c.person_id, b.availability_kind, b.starts_at, b.ends_at
    from app.availability_blocks b
    join app.availability_calendars c on c.id = b.availability_calendar_id and c.deleted_at is null
    where b.deleted_at is null and b.starts_at < v_shift.ends_at and b.ends_at > v_shift.starts_at
      and (c.org_id = v_shift.org_id or (c.org_id is null and c.visibility = 'Public'))
  ), scored as (
    select mb.membership_id, mb.person_id, mb.full_name,
      case
        when exists (select 1 from blocks b where b.person_id = mb.person_id and b.availability_kind = 'Unavailable') then 'Unavailable'
        when exists (select 1 from blocks b where b.person_id = mb.person_id and b.availability_kind = 'Available'
                     and b.starts_at <= v_shift.starts_at and b.ends_at >= v_shift.ends_at) then 'Available'
        when exists (select 1 from blocks b where b.person_id = mb.person_id) then 'Tentative'
        else 'Unstated'
      end as availability,
      exists (
        select 1 from app.shifts o
        where o.membership_id = mb.membership_id and o.deleted_at is null and o.shift_state <> 'Canceled'
          and o.id <> v_shift.id and o.starts_at < v_shift.ends_at and o.ends_at > v_shift.starts_at) as conflict,
      v_shift.role_code is not null and exists (
        select 1 from app.shifts o
        where o.membership_id = mb.membership_id and o.deleted_at is null and o.shift_state <> 'Canceled'
          and o.role_code = v_shift.role_code and o.id <> v_shift.id) as worked_role,
      coalesce((
        select sum(extract(epoch from (o.ends_at - o.starts_at)) / 60)::integer
        from app.shifts o
        where o.membership_id = mb.membership_id and o.deleted_at is null and o.shift_state <> 'Canceled'
          and o.starts_at >= v_week_start and o.starts_at < v_week_start + interval '7 days'), 0) as week_minutes
    from members mb
  )
  select s.membership_id, s.person_id, s.full_name, s.availability,
    v_rule.required and s.availability = 'Unstated' and v_shift.starts_at < now() + make_interval(days => v_rule.horizon_days),
    s.conflict, s.worked_role, s.week_minutes,
    (row_number() over (order by s.conflict,
      array_position(array['Available', 'Tentative', 'Unstated', 'Unavailable'], s.availability),
      s.worked_role desc, s.week_minutes, s.full_name nulls last, s.membership_id))::integer
  from scored s
  order by 9;
end;
$$;

comment on function app.rank_shift_candidates(uuid, date) is 'The org''s active members ranked for one shift (A132, ADR 0063), for the schedule''s drag list: free of an overlapping live shift first, then by stated availability over the shift (Available covering it, Tentative or partly stated, not stated, Unavailable) from their calendar kept for the org or a Public general one, then those who worked the shift''s role before, then the fewest scheduled minutes in the week (from p_week_start, or the ISO week of the shift in its zone). overdue marks a member who has not stated availability the org requires (scheduling.availability_required) for a shift inside the horizon. Needs crew.shift.write on the shift''s project; notes never appear.';

revoke all on function app.rank_shift_candidates(uuid, date) from public, anon;
grant execute on function app.rank_shift_candidates(uuid, date) to authenticated, service_role;
