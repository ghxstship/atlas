-- 1540_beta_locales_units_and_zone_display.sql
--
-- A97 (RRR-142, A65-028, WP21; ADR 0053): the Section 15 settings beyond en-US and es-US.
--   * locale.language offers the five Beta locales (fr-FR, de-DE, it-IT, pt-BR, ja-JP) after the launch
--     locales. Their catalogs come from the Google Translate pipeline (ADR 0037) and fall back to en-US key by
--     key; the language pickers mark them Beta.
--   * locale.units gains "jurisdiction", its new default: the unit system follows the project's jurisdiction
--     (imperial for the United States, metric otherwise) unless the org or the person chooses one. Values
--     already stored (imperial, metric) stay valid and keep winning.
--   * me.time_zone_display (personal): schedule times in the event's zone, the default, or the viewer's own.
-- Statements generated by `pnpm --filter @xos/schemas settings:sql a30` and `settings:sql a97`.

select private.define_setting('locale.language', 'Choice', 'org.localization.write', array['organization', 'personal'], true, p_default_text => 'en-US', p_choices => array['en-US', 'es-US', 'fr-FR', 'de-DE', 'it-IT', 'pt-BR', 'ja-JP']);
select private.define_setting('locale.units', 'Choice', 'org.localization.write', array['organization', 'personal'], false, p_default_text => 'jurisdiction', p_choices => array['jurisdiction', 'imperial', 'metric']);
select private.define_setting('me.time_zone_display', 'Choice', 'me.preferences.write', array['personal'], false, p_default_text => 'event', p_choices => array['event', 'viewer']);
