import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { EXTERNAL_AUDIENCES, INTERNAL_AUDIENCES, type Audience } from "@xos/sync";
import { bodyText, HELP_LOCALES, isSpecificTo, type HelpContent } from "@xos/help";
import { helpProblems, loadHelpContent, renderModule, uncoveredNodes } from "@xos/help/node";
import { flattenRoutes } from "@xos/ia";
import { loadSitemapFile } from "@xos/ia/node";
import { format, resolveConfig } from "prettier";
import { describe, expect, it } from "vitest";
import { moreMenu } from "../src/domain/access";
import {
  articlesForAudience,
  helpNodeFor,
  helpNodesFor,
  HELP_SCREENS,
  INTERNAL_SCREEN_NODES,
  isHelpHub,
  SHARED_SCREEN_NODES,
} from "../src/domain/help";

/**
 * Compass help (Section 11.16). `pnpm --filter @xos/compass generate:help` runs this file with
 * XOS_WRITE_GENERATED=1 to write src/help/content.generated.ts: every article with its body, which
 * ships inside the app so Help reads offline. Every other run fails on drift. Every navigable screen
 * (each expo-router route and each sitemap node) has an article of its own in every locale.
 */
const appRoot = fileURLToPath(new URL("../", import.meta.url));
const content = loadHelpContent(join(appRoot, "help"));
const target = join(appRoot, "src/help/content.generated.ts");
const HEADER = [
  "// Generated by apps/compass/test/help.test.ts (XOS_WRITE_GENERATED=1) from apps/compass/help.",
  "// Never edit by hand; on a merge conflict, take either side and rerun the generator.",
];
const bundled: HelpContent = { articles: content.articles, tours: [], tips: [], whatsNew: [] };
const expected = await format(
  renderModule(HEADER, "HelpContent", "@xos/help", "COMPASS_HELP", bundled),
  {
    ...((await resolveConfig(target)) ?? {}),
    filepath: target,
  },
);
if (process.env["XOS_WRITE_GENERATED"] === "1") writeFileSync(target, expected);

const sitemap = loadSitemapFile(join(appRoot, "ia/sitemap.yaml"));
const sitemapNodes = flattenRoutes(sitemap).map((r) => r.id);
const nodeIds = new Set([...sitemapNodes, ...INTERNAL_SCREEN_NODES, ...SHARED_SCREEN_NODES]);
const english = content.articles["en-US"];
const audiences: readonly Audience[] = [...INTERNAL_AUDIENCES, ...EXTERNAL_AUDIENCES];

/** Expo-router route files as their route patterns; layouts and the launch redirect are not screens. */
function screenRoutes(): string[] {
  const walk = (dir: string): string[] =>
    readdirSync(dir, { withFileTypes: true }).flatMap((entry) =>
      entry.isDirectory() ? walk(join(dir, entry.name)) : [join(dir, entry.name)],
    );
  return walk(join(appRoot, "app"))
    .filter((file) => file.endsWith(".tsx"))
    .map((file) => relative(join(appRoot, "app"), file).replace(/\.tsx$/, ""))
    .filter((path) => !/(^|\/)(_layout|\+native-intent)$/.test(path) && path !== "index")
    .map((path) =>
      `/${path.replace(/\(\w+\)\//g, "").replace(/(^|\/)index$/, "")}`.replace(/\/$/, ""),
    );
}

/** The help nodes a route can show: one, or one per value of its `$param` segment. */
function nodesOf(pattern: string): string[] {
  const node = HELP_SCREENS[pattern] ?? "";
  if (node === "reference.$section")
    return sitemapNodes.filter((id) => id.startsWith("reference."));
  if (node === "$page") {
    return [...new Set(audiences.flatMap((a) => moreMenu(a).map((m) => m.id)))];
  }
  return [node];
}

const covered = (node: string) => english.some((a) => isSpecificTo(a, node));

describe("Compass help content", () => {
  it("matches the generated module", () => {
    expect(existsSync(target) ? readFileSync(target, "utf8") : "").toBe(expected);
  });

  it("has every article in every locale, on real screens, linking to real articles", () => {
    expect(helpProblems(content, nodeIds)).toEqual([]);
  });

  it("maps every navigable screen to help, and maps no screen that does not exist", () => {
    const routes = screenRoutes();
    expect(routes.length).toBeGreaterThan(40);
    expect(routes.filter((r) => HELP_SCREENS[r] === undefined)).toEqual([]);
    expect(Object.keys(HELP_SCREENS).filter((r) => !routes.includes(r))).toEqual([]);
  });

  // Gate 31: every screen has an article of its own, not only the general ones.
  it("gives every navigable screen an article of its own", () => {
    const missing = screenRoutes().flatMap((r) =>
      nodesOf(r)
        .filter((n) => !covered(n))
        .map((n) => `${r}: ${n}`),
    );
    expect(missing).toEqual([]);
    expect(uncoveredNodes(english, sitemapNodes)).toEqual([]);
    for (const audience of audiences) {
      expect(uncoveredNodes(english, helpNodesFor(audience)), audience).toEqual([]);
    }
  });

  it("keeps articles short enough to read on a phone", () => {
    for (const locale of HELP_LOCALES) {
      for (const a of content.articles[locale]) {
        const words = bodyText(a.body).split(/\s+/).filter(Boolean).length;
        expect(words, `${locale}/${a.slug}`).toBeGreaterThanOrEqual(25);
        expect(words, `${locale}/${a.slug}`).toBeLessThanOrEqual(320);
      }
    }
  });

  it("calls a project gate a compuerta in Spanish (decision 27)", () => {
    // Logistics names the physical vehicle gate, which stays a gate (acceso, puerta) in Spanish.
    const PHYSICAL = new Set(["logistics"]);
    for (const a of english.filter((x) => !PHYSICAL.has(x.slug))) {
      if (!/\bgates?\b/i.test(`${a.title} ${a.summary} ${bodyText(a.body)}`)) continue;
      const es = content.articles["es-US"].find((x) => x.slug === a.slug);
      const text = `${es?.title} ${es?.summary} ${bodyText(es?.body ?? [])}`;
      expect(text, a.slug).toMatch(/compuerta/i);
    }
  });
});

describe("help for the current screen", () => {
  it("finds the help node of a concrete path", () => {
    expect(helpNodeFor("/today")).toBe("today");
    expect(helpNodeFor("/today/")).toBe("today");
    expect(helpNodeFor("/reference/sops")).toBe("reference.sops");
    expect(helpNodeFor("/pending/timesheets")).toBe("timesheets");
    expect(helpNodeFor("/workforce/chat/abc")).toBe("workforce.chat");
    expect(helpNodeFor("/help/contact")).toBe("help");
    expect(helpNodeFor("/help/today?x=1")).toBe("help");
    expect(helpNodeFor("/nowhere")).toBeNull();
    expect(helpNodeFor("/reference/")).toBe("reference");
  });

  it("looks past More, Settings and Help", () => {
    expect(isHelpHub("/more")).toBe(true);
    expect(isHelpHub("/settings")).toBe(true);
    expect(isHelpHub("/help/contact")).toBe(true);
    expect(isHelpHub("/settings/account")).toBe(true);
    expect(isHelpHub("/today")).toBe(false);
  });

  it("lists the articles for what an audience can reach", () => {
    const crew = helpNodesFor("crew");
    expect(crew.has("timesheets")).toBe(true);
    expect(crew.has("workforce.feed")).toBe(false);
    expect(crew.has("help")).toBe(true);
    const field = helpNodesFor("field");
    expect(field.has("workforce.feed")).toBe(true);
    expect(field.has("reference.sops")).toBe(true);
    const slugs = (audience: Audience) =>
      articlesForAudience(english, helpNodesFor(audience)).map((a) => a.slug);
    expect(slugs("crew")).toContain("getting-around");
    expect(slugs("crew")).toContain("elsewhere");
    expect(slugs("crew")).not.toContain("workforce-feed");
    expect(slugs("field-supervisor")).toContain("crew");
    expect(slugs("sponsor")).not.toContain("incidents");
  });
});
