/**
 * Writes src/navigation.generated.ts from ia/sitemap.yaml (Section 3.15: the sitemap is the single source
 * of the tab bar, More menu, scan modes and Today content). The app bundle cannot parse YAML at runtime,
 * so the per-audience navigation is resolved here with @xos/ia and emitted as data.
 *
 * test/navigation.test.ts fails when the file is stale; `pnpm --filter @xos/compass generate:navigation`
 * rewrites it.
 */
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";
import {
  chromeSlot,
  COMPASS_AUDIENCES,
  effectiveVisibility,
  indexSitemap,
  navigationTree,
  type CompassAudience,
  type NavTreeNode,
} from "@xos/ia";
import { loadSitemapFile } from "@xos/ia/node";

const sitemapPath = new URL("../ia/sitemap.yaml", import.meta.url);
const outPath = fileURLToPath(new URL("../src/navigation.generated.ts", import.meta.url));
const sitemap = loadSitemapFile(sitemapPath);
const index = indexSitemap(sitemap);

interface NavEntry {
  id: string;
  label: string;
  route: string;
  access: string;
  children: NavEntry[];
}

function entry(node: NavTreeNode, role: CompassAudience): NavEntry {
  const access = effectiveVisibility(sitemap, node.id, role) ?? "full";
  return {
    id: node.id,
    label: node.label,
    route: index.byId.get(node.id)?.node.route ?? "",
    access,
    children: (node.children ?? []).map((c) => entry(c, role)),
  };
}

const audiences: Record<string, unknown> = {};
for (const role of COMPASS_AUDIENCES) {
  const tabs = navigationTree(sitemap, { role }, ["tab-bar"])[0]?.children ?? [];
  const tabBar = chromeSlot(sitemap, "tabBar", { role }).map((n) => n.id);
  const profile = sitemap.contentProfiles?.[role];
  audiences[role] = {
    tabs: tabs.filter((t) => tabBar.includes(t.id)).map((t) => entry(t, role)),
    today: profile?.today ?? [],
    scanModes: profile?.scanModes ?? [],
  };
}

const contentLabels = Object.fromEntries(
  (sitemap.contentBlocks ?? []).map((b: { id: string; label: string }) => [b.id, b.label]),
);

/** The generated module's full text, formatted with the repository's Prettier settings. */
export async function renderNavigation(): Promise<string> {
  const source = `// Generated by \`pnpm --filter @xos/compass generate:navigation\` from ia/sitemap.yaml.
// Never edit by hand. On a merge conflict, rerun the generator.

export const navigation = ${JSON.stringify({ home: sitemap.home, contentLabels, audiences }, null, 2)} as const;
`;
  const config = await resolveConfig(outPath);
  return format(source, { ...config, filepath: outPath });
}

export const navigationOutPath = outPath;
