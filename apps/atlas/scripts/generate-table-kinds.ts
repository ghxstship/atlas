/**
 * The tables whose kind Atlas names in words (RRR-267): every table in private.trash_tables (Trash's Kind column and
 * filter) and every table with a retention policy (the legal-hold table picker), read from a migrated local database.
 * test/table-kinds.test.ts holds the catalog trash.kinds to this list in en-US and es-US.
 *
 *   pnpm --filter @xos/atlas table-kinds:generate   # writes test/table-kinds.generated.json
 *   pnpm --filter @xos/atlas table-kinds:check      # fails when the committed file differs from the database
 *
 * The retention list also holds the tables the nightly sweep would give the default policy
 * (private.sweep_default_retention, 1031), so the list after the migrations is the list after a night. Like the data
 * dictionary (apps/docs/scripts/generate-data-dictionary.ts), it reads the local stack through the Supabase CLI
 * (SUPABASE_WORKDIR selects another stack), and CI runs the check in the database job.
 */
import { execFileSync } from "node:child_process";
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";

const repoRoot = fileURLToPath(new URL("../../../", import.meta.url));
const target = fileURLToPath(new URL("../test/table-kinds.generated.json", import.meta.url));
const check = process.argv.includes("--check");

const SQL = `
select json_build_object(
  'trash', (select coalesce(json_agg(t.table_name order by t.table_name), '[]'::json)
            from private.trash_tables t),
  'retention', (select coalesce(json_agg(x.table_name order by x.table_name), '[]'::json)
                from (select r.table_name from private.retention_policies r
                      union
                      select format('app.%s', c.relname)
                      from pg_catalog.pg_class c
                      join pg_catalog.pg_namespace n on n.oid = c.relnamespace
                      where n.nspname = 'app' and c.relkind in ('r', 'p') and not c.relispartition
                        and (exists (select 1 from pg_catalog.pg_trigger g
                                     where g.tgrelid = c.oid and g.tgname = 't95_append_only')
                             or exists (select 1 from pg_catalog.pg_attribute a
                                        where a.attrelid = c.oid and a.attname = 'deleted_at'
                                          and not a.attisdropped))) x)
) as kinds;
`;

const scratch = mkdtempSync(join(tmpdir(), "xos-table-kinds-"));
let raw: string;
try {
  const file = join(scratch, "table-kinds.sql");
  writeFileSync(file, SQL);
  raw = execFileSync("supabase", ["db", "query", "-o", "json", "-f", file], {
    cwd: repoRoot,
    encoding: "utf8",
    stdio: ["ignore", "pipe", "inherit"],
  });
} finally {
  rmSync(scratch, { recursive: true, force: true });
}

const start = raw.search(/[[{]/);
const end = Math.max(raw.lastIndexOf("}"), raw.lastIndexOf("]"));
if (start === -1 || end < start) throw new Error("The query returned no JSON.");
const parsed = JSON.parse(raw.slice(start, end + 1)) as unknown;
const rows = Array.isArray(parsed) ? parsed : ((parsed as { rows?: unknown[] }).rows ?? [parsed]);
const value = (rows[0] as { kinds?: unknown } | undefined)?.kinds;
const kinds = (typeof value === "string" ? JSON.parse(value) : value) as
  { trash?: unknown; retention?: unknown } | undefined;
if (!kinds || !Array.isArray(kinds.trash) || !Array.isArray(kinds.retention)) {
  throw new Error("The query returned no table lists.");
}

const out = {
  $generated:
    "Generated by pnpm --filter @xos/atlas table-kinds:generate from a migrated local database. Never edit by hand: CI regenerates it and fails when it differs.",
  trash: kinds.trash,
  retention: kinds.retention,
};
const options = (await resolveConfig(target)) ?? {};
const text = await format(JSON.stringify(out), { ...options, filepath: target });
const counts = `${out.trash.length} Trash tables, ${out.retention.length} retention tables`;

if (check) {
  const current = existsSync(target) ? readFileSync(target, "utf8") : "";
  if (current !== text) {
    console.error(
      "apps/atlas/test/table-kinds.generated.json is out of date. Run pnpm --filter @xos/atlas table-kinds:generate.",
    );
    process.exit(1);
  }
  console.log(`Table kinds match the database: ${counts}.`);
} else {
  writeFileSync(target, text);
  console.log(`Wrote apps/atlas/test/table-kinds.generated.json: ${counts}.`);
}
