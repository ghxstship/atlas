import {
  flattenRoutes,
  parseRoute,
  validateSitemap,
  formatIssues,
  type Sitemap,
  type SitemapNode,
} from "@xos/ia";
import { getMessages } from "@xos/i18n";
import { parse } from "yaml";
import { packNodes } from "./client-sitemap-codec";
import { IMPLEMENTED } from "./implemented";
import { DELEGATED } from "./routes.config";

/**
 * Pure generation for the Atlas route tree (Section 3.15). `scripts/generate-routes.ts` writes the
 * result; `test/routes.test.ts` regenerates it in memory and fails on any difference, so a hand
 * edit or a stale file breaks the build (gate 28). Paths are relative to apps/atlas.
 */

export const GENERATED_PREFIX = "// Generated by `pnpm --filter @xos/atlas generate:routes`";

export const GENERATED_STAMP =
  "// Generated by `pnpm --filter @xos/atlas generate:routes` from ia/sitemap.yaml. Do not edit.";

/** The app directory segments for a sitemap route: `{org}` becomes `[org]`. */
export function routeSegments(route: string): string[] {
  return parseRoute(route).map((s) => (s.kind === "static" ? s.value : `[${s.name}]`));
}

/** The page file for a sitemap route, relative to apps/atlas. */
export function pageFile(route: string): string {
  return ["app", ...routeSegments(route), "page.tsx"].join("/");
}

/** The Next.js route key PageProps takes (`/[org]/finance/budgets`). */
export function routeKey(route: string): string {
  return `/${routeSegments(route).join("/")}`;
}

/**
 * The sitemap reduced to what route matching and breadcrumbs read: routed nodes with their id, kind,
 * label and route. Groups and actions are not navigation steps, so a group gives way to its children
 * and an action without a route is dropped; `findRoute` and `resolveBreadcrumbs` answer the same.
 */
export function clientSitemap(sitemap: Sitemap): Sitemap {
  const slim = (node: SitemapNode): SitemapNode[] => {
    const children = (node.children ?? []).flatMap(slim);
    if (node.route === undefined) return children;
    return [
      {
        id: node.id,
        kind: node.kind,
        label: node.label,
        route: node.route,
        ...(children.length > 0 ? { children } : {}),
      },
    ];
  };
  return {
    schemaVersion: sitemap.schemaVersion,
    shell: sitemap.shell,
    home: sitemap.home,
    params: sitemap.params,
    audience: sitemap.audience,
    nodes: sitemap.nodes.flatMap(slim),
  };
}

/** The ids of nodes with a list, in declared order. */
export function listNodeIds(sitemap: Sitemap): string[] {
  return flattenRoutes(sitemap)
    .filter((r) => r.views !== undefined)
    .map((r) => r.id);
}

function pageSource(id: string, route: string): string {
  return `${GENERATED_STAMP}
// To implement this page by hand, add "${id}" to your file in ia/implemented/.
import { SitemapPage } from "@/components/shell/sitemap-page";

export default async function Page({ params }: PageProps<"${routeKey(route)}">) {
  return <SitemapPage node="${id}" params={await params} />;
}
`;
}

/** Nodes that get a generated page: routed, served by Atlas, not delegated, not hand-written. */
export function generatedNodes(sitemap: Sitemap) {
  return flattenRoutes(sitemap).filter(
    (r) => r.servedBy === undefined && !(r.id in DELEGATED) && !IMPLEMENTED.has(r.id),
  );
}

export interface LegalDocument {
  readonly slug: string;
  readonly title: string;
  readonly version: string;
  readonly publish: "public" | "internal";
  readonly requiresAcceptanceAtSignup: boolean;
  readonly acceptanceBy: readonly string[];
}

function legalSource(documents: readonly LegalDocument[]): string {
  return `${GENERATED_STAMP.replace("ia/sitemap.yaml", "legal/index.yaml")}
import type { LegalDocument } from "@/ia/generate";

/** The legal registry (Section 14.4): current version of every document, from legal/index.yaml. */
export const LEGAL_DOCUMENTS: readonly LegalDocument[] = ${JSON.stringify(documents)};
`;
}

export function parseLegalRegistry(text: string): LegalDocument[] {
  const data = parse(text) as {
    documents: {
      slug: string;
      title: string;
      version: string;
      publish: "public" | "internal";
      requires_acceptance_at_signup: boolean;
      acceptance_by: string[];
    }[];
  };
  return data.documents.map((d) => ({
    slug: d.slug,
    title: d.title,
    version: d.version,
    publish: d.publish,
    requiresAcceptanceAtSignup: d.requires_acceptance_at_signup,
    acceptanceBy: d.acceptance_by,
  }));
}

/** A plan as the Billing and Plan page shows it, from packages/schemas/plans.yaml (Section 16). */
export interface PlanSummary {
  readonly code: string;
  readonly free: boolean;
  /** The plan this one extends; its features are included. */
  readonly extends: string | null;
  /** Features this plan adds over the one it extends. */
  readonly adds: readonly string[];
  /** Limit code to value; null is unlimited. */
  readonly limits: Readonly<Record<string, number | null>>;
  /** USD monthly price in minor units; null is unpriced (Section 3.7). */
  readonly usdMonthlyMinor: number | null;
}

export function parsePlanRegistry(text: string): PlanSummary[] {
  const data = parse(text) as {
    plans: {
      code: string;
      free?: boolean;
      extends?: string;
      features: string[];
      limits: Record<string, number | null>;
      prices: Record<string, { monthly_minor: number | null }>;
    }[];
  };
  return data.plans.map((p) => ({
    code: p.code,
    free: p.free === true,
    extends: p.extends ?? null,
    adds: p.features,
    limits: p.limits,
    usdMonthlyMinor: p.prices["USD"]?.monthly_minor ?? null,
  }));
}

/**
 * Every generated file, unformatted, keyed by path: the sitemap module the runtime reads, the
 * legal registry and plan modules, and one page per generated node. Throws when the sitemap fails
 * validation.
 */
export function generateFiles(
  sitemap: Sitemap,
  legal: readonly LegalDocument[],
  plans: readonly PlanSummary[] = [],
): Map<string, string> {
  const issues = validateSitemap(sitemap, { messages: getMessages("en-US") });
  if (issues.length > 0) throw new Error(`ia/sitemap.yaml is invalid:\n${formatIssues(issues)}`);
  const files = new Map<string, string>();
  files.set(
    "ia/sitemap.generated.ts",
    `${GENERATED_STAMP}
import type { Sitemap } from "@xos/ia";

/** The Atlas sitemap as data, so the proxy and pages read it without parsing YAML at runtime. */
export const sitemap: Sitemap = ${JSON.stringify(sitemap)};
`,
  );
  const { nodes: clientNodes, ...clientHeader } = clientSitemap(sitemap);
  files.set(
    "ia/sitemap.client.generated.ts",
    `${GENERATED_STAMP}
import type { Sitemap } from "@xos/ia";
import { unpackNodes } from "./client-sitemap-codec";

/**
 * The routed part of the Atlas sitemap for client components (breadcrumbs, the help panel's page):
 * ids, kinds, labels and routes only, so the browser never downloads visibility, list or persona
 * data it does not read (A24-009). The nodes ship packed (ia/client-sitemap-codec.ts). Server code
 * reads ia/sitemap.generated.ts.
 */
export const clientSitemap: Sitemap = {
  ...${JSON.stringify(clientHeader)},
  nodes: unpackNodes(${JSON.stringify(packNodes(clientNodes))}),
};

/** Nodes with a list (a collection page), which open their own rows in the side peek. */
export const listNodes: ReadonlySet<string> = new Set(${JSON.stringify(listNodeIds(sitemap))});
`,
  );
  files.set("lib/legal.generated.ts", legalSource(legal));
  files.set(
    "lib/plans.generated.ts",
    `${GENERATED_STAMP.replace("ia/sitemap.yaml", "packages/schemas/plans.yaml")}
import type { PlanSummary } from "@/ia/generate";

/** Plans from the free plan upward (Section 16), from packages/schemas/plans.yaml. */
export const PLANS: readonly PlanSummary[] = ${JSON.stringify(plans)};
`,
  );
  for (const node of generatedNodes(sitemap)) {
    files.set(pageFile(node.route), pageSource(node.id, node.route));
  }
  return files;
}

