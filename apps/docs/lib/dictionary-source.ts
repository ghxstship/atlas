/**
 * How the data dictionary is read from the catalog (scripts/generate-data-dictionary.ts) and the shape of the
 * committed file, content/data-dictionary.json. Scope follows the comment doctrine (pgTAP 1280): app and xpms
 * tables (partitions are left out; their parent carries the comments) and the views of app, xpms, api_external
 * and api_public.
 */

export interface DictionaryColumn {
  readonly name: string;
  readonly type: string;
  readonly nullable: boolean;
  readonly comment: string | null;
  /** `schema.table.column` this column points to through a foreign key, or null. */
  readonly references: string | null;
}

export interface DictionaryTable {
  readonly schema: string;
  readonly name: string;
  readonly kind: "table" | "view" | "materialized view";
  readonly partitioned: boolean;
  readonly rls: boolean;
  readonly comment: string | null;
  readonly primaryKey: readonly string[];
  readonly columns: readonly DictionaryColumn[];
}

export interface DataDictionary {
  readonly $generated: string;
  readonly tableCount: number;
  readonly viewCount: number;
  readonly columnCount: number;
  readonly tables: readonly DictionaryTable[];
}

export const GENERATED_NOTE =
  "Generated by pnpm --filter @xos/docs dictionary:generate from the catalog comments of a migrated local database. Never edit by hand: CI regenerates it and fails when it differs.";

/** One row holding the whole dictionary as JSON, ordered so the output never changes without a schema change. */
export const DICTIONARY_SQL = `
with rels as (
  select c.oid, n.nspname as schema_name, c.relname as rel_name, c.relkind,
         obj_description(c.oid, 'pg_class') as rel_comment, c.relrowsecurity
  from pg_catalog.pg_class c
  join pg_catalog.pg_namespace n on n.oid = c.relnamespace
  where (n.nspname in ('app', 'xpms') and c.relkind in ('r', 'p') and not c.relispartition)
     or (n.nspname in ('app', 'xpms', 'api_external', 'api_public') and c.relkind in ('v', 'm'))
)
select coalesce(json_agg(json_build_object(
  'schema', r.schema_name,
  'name', r.rel_name,
  'kind', case r.relkind when 'v' then 'view' when 'm' then 'materialized view' else 'table' end,
  'partitioned', r.relkind = 'p',
  'rls', r.relrowsecurity,
  'comment', r.rel_comment,
  'primaryKey', coalesce((
    select json_agg(a.attname order by array_position(i.indkey::int2[], a.attnum))
    from pg_catalog.pg_index i
    join pg_catalog.pg_attribute a on a.attrelid = i.indrelid and a.attnum = any (i.indkey)
    where i.indrelid = r.oid and i.indisprimary), '[]'::json),
  'columns', coalesce((
    select json_agg(json_build_object(
      'name', a.attname,
      'type', pg_catalog.format_type(a.atttypid, a.atttypmod),
      'nullable', not a.attnotnull,
      'comment', pg_catalog.col_description(a.attrelid, a.attnum),
      'references', (
        select fn.nspname || '.' || fc.relname || '.' || fa.attname
        from pg_catalog.pg_constraint con
        join pg_catalog.pg_class fc on fc.oid = con.confrelid
        join pg_catalog.pg_namespace fn on fn.oid = fc.relnamespace
        join pg_catalog.pg_attribute fa
          on fa.attrelid = con.confrelid and fa.attnum = con.confkey[array_position(con.conkey, a.attnum)]
        where con.conrelid = r.oid and con.contype = 'f' and a.attnum = any (con.conkey)
        order by con.conname
        limit 1)
    ) order by a.attnum)
    from pg_catalog.pg_attribute a
    where a.attrelid = r.oid and a.attnum > 0 and not a.attisdropped), '[]'::json)
) order by r.schema_name, r.rel_name), '[]'::json) as dictionary
from rels r;
`;

/**
 * The tables from `supabase db query -o json` output: an array of rows, or an object with a `rows` array, whose
 * one row carries the dictionary as JSON (or as JSON text).
 */
export function parseQueryOutput(raw: string): DictionaryTable[] {
  const start = raw.search(/[[{]/);
  const end = Math.max(raw.lastIndexOf("}"), raw.lastIndexOf("]"));
  if (start === -1 || end < start) throw new Error("The query returned no JSON.");
  const parsed = JSON.parse(raw.slice(start, end + 1)) as unknown;
  const rows = Array.isArray(parsed) ? parsed : ((parsed as { rows?: unknown[] }).rows ?? [parsed]);
  const value = (rows[0] as { dictionary?: unknown } | undefined)?.dictionary;
  const tables = typeof value === "string" ? (JSON.parse(value) as unknown) : value;
  if (!Array.isArray(tables)) throw new Error("The query returned no dictionary column.");
  return tables as DictionaryTable[];
}

export function toDictionary(tables: readonly DictionaryTable[]): DataDictionary {
  const views = tables.filter((t) => t.kind !== "table").length;
  return {
    $generated: GENERATED_NOTE,
    tableCount: tables.length - views,
    viewCount: views,
    columnCount: tables.reduce((n, t) => n + t.columns.length, 0),
    tables,
  };
}

/** The page slug of a table: `schema.name`, which is unique and URL safe for Postgres identifiers. */
export function tableSlug(table: Pick<DictionaryTable, "schema" | "name">): string {
  return `${table.schema}.${table.name}`;
}
