import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import {
  legalPlainText,
  legalTextSource,
  parseLegalMarkdown,
  stripFrontmatter,
} from "@xos/ui/legal-text";
import { format, resolveConfig } from "prettier";
import { describe, expect, it } from "vitest";
import { parse } from "yaml";
import { GATEWAY_LEGAL_DOCUMENTS } from "../lib/auth/legal";

/**
 * The text Gateway serves at /legal (Section 14.4). `pnpm --filter @xos/gateway generate:legal` runs
 * this file with XOS_WRITE_GENERATED=1 to write lib/legal-text.generated.ts; every other run fails on
 * drift, so a changed document cannot ship without its text. It is checked in because a server
 * bundle cannot read legal/ at runtime.
 */
const repo = new URL("../../../", import.meta.url);
const read = (file: string) => readFileSync(new URL(file, repo), "utf8");
const target = fileURLToPath(new URL("../lib/legal-text.generated.ts", import.meta.url));
const STAMP =
  "// Generated by `pnpm --filter @xos/gateway generate:legal` from legal/index.yaml and its documents. Do not edit.";

const registry = (
  parse(read("legal/index.yaml")) as {
    documents: {
      slug: string;
      file: string;
      publish: string;
      version: string;
      history: { version: string; effective_date?: string; summary: string }[];
    }[];
  }
).documents;
const served = new Set(GATEWAY_LEGAL_DOCUMENTS.map((d) => d.slug));

const options = (await resolveConfig(target)) ?? {};
const expected = await format(
  legalTextSource(STAMP, registry, read, (slug) => served.has(slug)),
  { ...options, filepath: target },
);
if (process.env["XOS_WRITE_GENERATED"] === "1") writeFileSync(target, expected);

describe("Gateway's generated legal text", () => {
  it("matches the documents with no hand edits", () => {
    expect(existsSync(target) && readFileSync(target, "utf8") === expected).toBe(true);
  });

  it("carries the text of every document Gateway serves, in full, and no other", async () => {
    const { LEGAL_TEXT } = await import("../lib/legal-text.generated");
    expect(Object.keys(LEGAL_TEXT).sort()).toEqual([...served].sort());
    for (const slug of served) {
      const entry = registry.find((d) => d.slug === slug);
      expect(LEGAL_TEXT[slug]).toBe(stripFrontmatter(read(entry?.file ?? "")));
      expect(legalPlainText(parseLegalMarkdown(LEGAL_TEXT[slug] ?? ""))).toContain(
        GATEWAY_LEGAL_DOCUMENTS.find((d) => d.slug === slug)?.title,
      );
    }
  });

  it("lists the versions of every document Gateway serves, the current one first", async () => {
    const { LEGAL_HISTORY } = await import("../lib/legal-text.generated");
    expect(Object.keys(LEGAL_HISTORY).sort()).toEqual([...served].sort());
    for (const doc of GATEWAY_LEGAL_DOCUMENTS) {
      expect(LEGAL_HISTORY[doc.slug]?.[0]?.version).toBe(doc.version);
    }
  });

  it("serves the Terms of Service, and accepts nothing new at account creation", () => {
    const terms = GATEWAY_LEGAL_DOCUMENTS.find((d) => d.slug === "terms-of-service");
    expect(terms?.accept).toBe(false);
    expect(GATEWAY_LEGAL_DOCUMENTS.filter((d) => d.accept).map((d) => d.slug)).toEqual([
      "worker-terms",
    ]);
  });
});
