import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { relative } from "node:path";
import { fileURLToPath } from "node:url";
import { HELP_LOCALES, bodyText } from "@xos/help";
import {
  helpProblems,
  loadHelpContent,
  renderHelpBodies,
  renderHelpModule,
  stalePartials,
  uncoveredNodes,
} from "@xos/help/node";
import { getMessages, type Locale } from "@xos/i18n";
import { SHORTCUT_REGISTRY } from "@xos/schemas/shortcuts";
import { shortcutPartial } from "@xos/schemas/shortcuts/docs";
import { flattenRoutes } from "@xos/ia";
import { format, resolveConfig } from "prettier";
import { describe, expect, it } from "vitest";
import enHelp from "../../../packages/i18n/messages/en-US/help.json";
import esHelp from "../../../packages/i18n/messages/es-US/help.json";
import { sitemap } from "../ia/sitemap.generated";

/**
 * Gateway help content (Section 11.16; gate 31). `pnpm --filter @xos/gateway generate:help` runs this
 * file with XOS_WRITE_GENERATED=1 to write help/content.generated.ts (the index the panel loads when
 * Help opens) and help/bodies.generated.ts (the bodies, loaded after); every other run fails on drift.
 * Every signed-in Gateway route has an article of its own in every locale, every article names real
 * pages and links only to articles that exist, and What's New has its copy. The keyboard articles'
 * shortcut lists are generated from the shortcut registry (Section 3.15) and written first, so the
 * modules below read them; changing a default key without regenerating fails here.
 */
const HELP_DIR = fileURLToPath(new URL("../help/", import.meta.url));
const HEADER = [
  "// Generated by apps/gateway/test/help.test.ts (XOS_WRITE_GENERATED=1) from apps/gateway/help.",
  "// Never edit by hand; on a merge conflict, take either side and rerun the generator.",
];
const write = process.env["XOS_WRITE_GENERATED"] === "1";
const stale = stalePartials(
  HELP_DIR,
  shortcutPartial(SHORTCUT_REGISTRY, (locale) => getMessages(locale as Locale)),
);
if (write) for (const s of stale) writeFileSync(s.file, s.expected);
const content = loadHelpContent(HELP_DIR);
const indexTarget = fileURLToPath(new URL("../help/content.generated.ts", import.meta.url));
const bodiesTarget = fileURLToPath(new URL("../help/bodies.generated.ts", import.meta.url));
const formatted = async (source: string, file: string) =>
  format(source, { ...((await resolveConfig(file)) ?? {}), filepath: file });
const expectedIndex = await formatted(renderHelpModule(content, HEADER, "@xos/help"), indexTarget);
const expectedBodies = await formatted(
  renderHelpBodies(content, HEADER, "@xos/help"),
  bodiesTarget,
);
if (write) {
  writeFileSync(indexTarget, expectedIndex);
  writeFileSync(bodiesTarget, expectedBodies);
}

const nodeIds = new Set(flattenRoutes(sitemap).map((r) => r.id));
const sessionRoutes = flattenRoutes(sitemap).filter((r) => r.auth === "session");

const lookup = (catalog: unknown, path: string): unknown =>
  path
    .split(".")
    .reduce<unknown>((o, k) => (o as Record<string, unknown> | undefined)?.[k], catalog);

describe("Gateway help content", () => {
  it("names the registry's default keys in the shortcut lists (A65-007)", () => {
    expect(write ? [] : stale.map((s) => relative(HELP_DIR, s.file))).toEqual([]);
    for (const slug of ["settings-keyboard-shortcuts", "getting-around"]) {
      const article = content.articles["en-US"].find((a) => a.slug === slug);
      const items = article?.body.flatMap((b) => ("items" in b ? b.items : [])) ?? [];
      expect(items, slug).toContainEqual([
        { t: "strong", v: "G H" },
        { t: "text", v: ": Go to Home" },
      ]);
    }
  });

  it("matches the generated modules", () => {
    expect(existsSync(indexTarget) ? readFileSync(indexTarget, "utf8") : "").toBe(expectedIndex);
    expect(existsSync(bodiesTarget) ? readFileSync(bodiesTarget, "utf8") : "").toBe(expectedBodies);
  });

  it("keeps article bodies out of the index", () => {
    expect(expectedIndex).not.toContain('"body"');
  });

  it("has every article in every locale, on real pages, linking to real articles", () => {
    expect(helpProblems(content, nodeIds)).toEqual([]);
    expect(content.articles["en-US"].length).toBeGreaterThanOrEqual(sessionRoutes.length - 10);
  });

  // Gate 31: every signed-in page has help of its own, not only the general articles. Public and
  // token pages carry no shell, so no help panel.
  it("gives every signed-in Gateway route an article of its own", () => {
    expect(
      uncoveredNodes(
        content.articles["en-US"],
        sessionRoutes.map((r) => r.id),
      ),
    ).toEqual([]);
  });

  it("writes short articles with a body", () => {
    for (const locale of HELP_LOCALES) {
      for (const a of content.articles[locale]) {
        const words = bodyText(a.body).split(/\s+/).filter(Boolean).length;
        expect(words, `${locale}/${a.slug}`).toBeGreaterThanOrEqual(30);
        expect(words, `${locale}/${a.slug}`).toBeLessThanOrEqual(600);
      }
    }
  });

  it("calls a project gate a compuerta in Spanish (decision 27)", () => {
    for (const a of content.articles["en-US"]) {
      if (!/\bgates?\b/i.test(`${a.title} ${a.summary} ${bodyText(a.body)}`)) continue;
      const es = content.articles["es-US"].find((x) => x.slug === a.slug);
      const text = `${es?.title} ${es?.summary} ${bodyText(es?.body ?? [])}`;
      expect(text, a.slug).toMatch(/compuerta/i);
      expect(text, a.slug).not.toMatch(/\bpuertas?\b/i);
    }
  });

  it("has What's New copy in both locales", () => {
    expect(content.whatsNew.length).toBeGreaterThan(0);
    for (const catalog of [enHelp, esHelp]) {
      for (const entry of content.whatsNew) {
        for (const field of ["title", "body"]) {
          expect(lookup(catalog, `gateway.whatsNew.${entry.key}.${field}`), entry.key).toBeTypeOf(
            "string",
          );
        }
      }
    }
  });
});
