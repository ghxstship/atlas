import { parseRoute, type Sitemap } from "@xos/ia";

/**
 * Pure generation for Gateway (Section 3.15: navigation is generated from ia/sitemap.yaml). The
 * sitemap becomes a TypeScript module so the proxy and pages read it without parsing YAML at
 * runtime. `test/routes.test.ts` regenerates it in memory and fails on any difference, so a hand
 * edit or a stale file breaks the build (gate 28). Every Gateway page is written by hand.
 */

export const GENERATED_PREFIX = "// Generated by `pnpm --filter @xos/gateway generate:sitemap`";

export const GENERATED_STAMP = `${GENERATED_PREFIX} from ia/sitemap.yaml. Do not edit.`;

/** The app directory segments for a sitemap route: `{handle}` becomes `[handle]`. */
export function routeSegments(route: string): string[] {
  return parseRoute(route).map((s) => (s.kind === "static" ? s.value : `[${s.name}]`));
}

export function sitemapSource(sitemap: Sitemap): string {
  return `${GENERATED_STAMP}
import type { Sitemap } from "@xos/ia";

/** The Gateway sitemap as data, so the proxy and pages read it without parsing YAML at runtime. */
export const sitemap: Sitemap = ${JSON.stringify(sitemap)};
`;
}
