import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";
import { build } from "vite";

/**
 * Builds the Edge Function bundle of @xos/platform (Section 3.15: generated, never hand-written).
 * npm packages stay external; supabase/functions/deno.json maps each to its pinned npm: specifier.
 * With --check, builds to a temporary directory and exits 1 when the committed bundle differs.
 */
export const EDGE_EXTERNALS = [
  "stripe",
  "zod",
  "resend",
  "react",
  "react/jsx-runtime",
  "react-dom",
  "@react-email/components",
  "intl-messageformat",
  "@supabase/supabase-js",
  "yaml",
  "exceljs",
  "pdfkit",
] as const;

export const BUNDLE_PATH = fileURLToPath(
  new URL("../../../supabase/functions/_vendor/xos-platform.js", import.meta.url),
);

/**
 * Per-function bundles (packages/platform/edge/entries/<function>.ts to _vendor/<function>.js), for a
 * function that must not load the whole platform bundle: search-embed (A87) loads no npm package.
 */
export const FUNCTION_BUNDLES = {
  "search-embed": fileURLToPath(
    new URL("../../../supabase/functions/_vendor/search-embed.js", import.meta.url),
  ),
} as const;

function stamp(source: string): string {
  return [
    `// Generated by \`pnpm --filter @xos/platform bundle:edge\` from packages/platform/edge/${source}.`,
    "// Never edit by hand; the @xos/platform tests fail when this file differs from the build output.",
    "",
  ].join("\n");
}

/**
 * Builds a bundle and returns its formatted text: the platform bundle, or a function's own bundle from
 * edge/entries/<name>.ts.
 */
export async function renderBundle(name?: keyof typeof FUNCTION_BUNDLES): Promise<string> {
  const source = name ? `entries/${name}.ts` : "entry.ts";
  const target = name ? FUNCTION_BUNDLES[name] : BUNDLE_PATH;
  const outDir = mkdtempSync(join(tmpdir(), "xos-edge-"));
  // The bundle is production code whatever the caller's mode (Vitest sets NODE_ENV=test).
  const previousNodeEnv = process.env["NODE_ENV"];
  process.env["NODE_ENV"] = "production";
  try {
    await build({
      configFile: false,
      mode: "production",
      logLevel: "silent",
      root: fileURLToPath(new URL(".", import.meta.url)),
      plugins: [
        {
          // The Edge runtime has no file URLs. The registry is embedded, so the loader's default path
          // (used only by loadPlanRegistry, which the functions never call) becomes a plain name.
          name: "xos-edge-plans-path",
          transform(code, id) {
            if (!id.endsWith("/schemas/src/plans/load.ts")) return null;
            const replaced = code.replace(
              /fileURLToPath\(new URL\("\.\.\/\.\.\/plans\.yaml", import\.meta\.url\)\)/,
              JSON.stringify("plans.yaml"),
            );
            if (replaced === code)
              throw new Error("The plans loader changed; update the Edge bundle plugin.");
            return replaced;
          },
        },
      ],
      build: {
        outDir,
        emptyOutDir: true,
        minify: false,
        sourcemap: false,
        target: "es2022",
        lib: {
          entry: fileURLToPath(new URL(`./${source}`, import.meta.url)),
          formats: ["es"],
          fileName: () => "xos-platform.js",
        },
        rollupOptions: {
          external: (id) =>
            id.startsWith("node:") ||
            EDGE_EXTERNALS.some((name) => id === name || id.startsWith(`${name}/`)),
        },
      },
    });
    const raw = readFileSync(join(outDir, "xos-platform.js"), "utf8");
    const options = (await resolveConfig(target)) ?? {};
    return format(`${stamp(source)}${raw}`, { ...options, filepath: target });
  } finally {
    if (previousNodeEnv === undefined) delete process.env["NODE_ENV"];
    else process.env["NODE_ENV"] = previousNodeEnv;
    rmSync(outDir, { recursive: true, force: true });
  }
}

if (process.argv[1] !== undefined && fileURLToPath(import.meta.url) === process.argv[1]) {
  // One build at a time: each sets NODE_ENV for the duration of its build.
  const targets: [string, () => Promise<string>][] = [
    [BUNDLE_PATH, () => renderBundle()],
    ...Object.keys(FUNCTION_BUNDLES).map((name): [string, () => Promise<string>] => [
      FUNCTION_BUNDLES[name as keyof typeof FUNCTION_BUNDLES],
      () => renderBundle(name as keyof typeof FUNCTION_BUNDLES),
    ]),
  ];
  let stale = false;
  for (const [path, render] of targets) {
    const bundle = await render();
    const shown = path.slice(path.indexOf("supabase/functions/"));
    if (process.argv.includes("--check")) {
      if (readFileSync(path, "utf8") !== bundle) {
        console.error(`${shown} is out of date. Run bundle:edge.`);
        stale = true;
      }
    } else {
      writeFileSync(path, bundle);
      console.log(`Wrote ${shown}.`);
    }
  }
  if (stale) process.exit(1);
  if (process.argv.includes("--check"))
    console.log("The Edge Function bundles match their sources.");
}
