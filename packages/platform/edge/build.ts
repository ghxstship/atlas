import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";
import { build } from "vite";

/**
 * Builds the Edge Function bundle of @xos/platform (Section 3.15: generated, never hand-written).
 * npm packages stay external; supabase/functions/deno.json maps each to its pinned npm: specifier.
 * With --check, builds to a temporary directory and exits 1 when the committed bundle differs.
 */
export const EDGE_EXTERNALS = [
  "stripe",
  "zod",
  "resend",
  "react",
  "react/jsx-runtime",
  "react-dom",
  "@react-email/components",
  "intl-messageformat",
  "@supabase/supabase-js",
  "yaml",
] as const;

export const BUNDLE_PATH = fileURLToPath(
  new URL("../../../supabase/functions/_vendor/xos-platform.js", import.meta.url),
);

const STAMP = [
  "// Generated by `pnpm --filter @xos/platform bundle:edge` from packages/platform/edge/entry.ts.",
  "// Never edit by hand; the @xos/platform tests fail when this file differs from the build output.",
  "",
].join("\n");

/** Builds the bundle and returns its formatted text. */
export async function renderBundle(): Promise<string> {
  const outDir = mkdtempSync(join(tmpdir(), "xos-edge-"));
  // The bundle is production code whatever the caller's mode (Vitest sets NODE_ENV=test).
  const previousNodeEnv = process.env["NODE_ENV"];
  process.env["NODE_ENV"] = "production";
  try {
    await build({
      configFile: false,
      mode: "production",
      logLevel: "silent",
      root: fileURLToPath(new URL(".", import.meta.url)),
      plugins: [
        {
          // The Edge runtime has no file URLs. The registry is embedded, so the loader's default path
          // (used only by loadPlanRegistry, which the functions never call) becomes a plain name.
          name: "xos-edge-plans-path",
          transform(code, id) {
            if (!id.endsWith("/schemas/src/plans/load.ts")) return null;
            const replaced = code.replace(
              /fileURLToPath\(new URL\("\.\.\/\.\.\/plans\.yaml", import\.meta\.url\)\)/,
              JSON.stringify("plans.yaml"),
            );
            if (replaced === code)
              throw new Error("The plans loader changed; update the Edge bundle plugin.");
            return replaced;
          },
        },
      ],
      build: {
        outDir,
        emptyOutDir: true,
        minify: false,
        sourcemap: false,
        target: "es2022",
        lib: {
          entry: fileURLToPath(new URL("./entry.ts", import.meta.url)),
          formats: ["es"],
          fileName: () => "xos-platform.js",
        },
        rollupOptions: {
          external: (id) =>
            id.startsWith("node:") ||
            EDGE_EXTERNALS.some((name) => id === name || id.startsWith(`${name}/`)),
        },
      },
    });
    const raw = readFileSync(join(outDir, "xos-platform.js"), "utf8");
    const options = (await resolveConfig(BUNDLE_PATH)) ?? {};
    return format(`${STAMP}${raw}`, { ...options, filepath: BUNDLE_PATH });
  } finally {
    if (previousNodeEnv === undefined) delete process.env["NODE_ENV"];
    else process.env["NODE_ENV"] = previousNodeEnv;
    rmSync(outDir, { recursive: true, force: true });
  }
}

if (process.argv[1] !== undefined && fileURLToPath(import.meta.url) === process.argv[1]) {
  const bundle = await renderBundle();
  if (process.argv.includes("--check")) {
    const current = readFileSync(BUNDLE_PATH, "utf8");
    if (current !== bundle) {
      console.error("supabase/functions/_vendor/xos-platform.js is out of date. Run bundle:edge.");
      process.exit(1);
    }
    console.log("The Edge Function bundle matches its sources.");
  } else {
    writeFileSync(BUNDLE_PATH, bundle);
    console.log("Wrote supabase/functions/_vendor/xos-platform.js.");
  }
}
