import {
  mkdirSync,
  mkdtempSync,
  readFileSync,
  readdirSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, posix, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";
import { build } from "vite";
import { loadPlanRegistry } from "@xos/schemas/plans";

/**
 * Builds the Edge Function bundles of @xos/platform (Section 3.15: generated, never hand-written).
 *
 * Per-function bundles (A85, RRR-130). Every function used to import one 1.6 MB bundle that loaded
 * Stripe, Resend, React Email and every message catalog, so each cold start parsed all of it and
 * kiosk-punch hit the worker CPU limit (HTTP 546). Now each file in edge/entries is an entry:
 * `core` for supabase/functions/_shared, and one per function that uses platform code. Code they
 * share is split into supabase/functions/_vendor/chunks, so a function loads only the modules it
 * reaches. Heavy modules (React Email, Resend, exceljs, pdfkit, the report catalogs) load through
 * dynamic imports when a request needs them.
 *
 * npm packages stay external. supabase/functions/deno.json pins every one (the version catalog), and
 * each function gets its own generated deno.json with only the packages its graph imports, which
 * `supabase functions deploy` uses as that function's import map.
 *
 * With --check, builds in memory and exits 1 when a committed file differs, is missing or is extra.
 */
export const EDGE_EXTERNALS = [
  "stripe",
  "zod",
  "resend",
  "react",
  "react/jsx-runtime",
  "react-dom",
  "@react-email/components",
  "intl-messageformat",
  "@supabase/supabase-js",
  "yaml",
  "exceljs",
  "pdfkit",
] as const;

export const FUNCTIONS_DIR = fileURLToPath(
  new URL("../../../supabase/functions/", import.meta.url),
);
export const VENDOR_DIR = join(FUNCTIONS_DIR, "_vendor");
export const CATALOG_PATH = join(FUNCTIONS_DIR, "deno.json");
const ENTRIES_DIR = fileURLToPath(new URL("./entries/", import.meta.url));
const REPO_ROOT = fileURLToPath(new URL("../../../", import.meta.url));
const PLAN_REGISTRY = "virtual:xos-plan-registry";

/** The bundle entries, by name: `core` and one per function (edge/entries/<name>.ts). */
export const EDGE_ENTRIES: readonly string[] = readdirSync(ENTRIES_DIR)
  .filter((file) => file.endsWith(".ts"))
  .map((file) => file.slice(0, -".ts".length))
  .sort();

/** The functions: every directory of supabase/functions except _shared and _vendor. */
export function edgeFunctions(root: string = FUNCTIONS_DIR): string[] {
  return readdirSync(root)
    .filter((name) => !name.startsWith("_") && statSync(join(root, name)).isDirectory())
    .sort();
}

const STAMP = [
  "// Generated by `pnpm --filter @xos/platform bundle:edge` from packages/platform/edge/entries.",
  "// Never edit by hand; the @xos/platform tests fail when this file differs from the build output.",
  "",
].join("\n");

const posixPath = (path: string) => path.split(sep).join(posix.sep);

/** A readable, stable chunk name from the module that loads the rest: `email-templates`, `platform-stores`. */
function chunkName(moduleId: string | undefined, fallback: string): string {
  if (moduleId === undefined || moduleId.startsWith("\0")) return fallback;
  const path = posixPath(relative(REPO_ROOT, moduleId.split("?")[0] ?? moduleId))
    .replace(/^packages\//, "")
    .replace(/^infra\//, "")
    .replace(/\/(src|messages)\//, "/")
    .replace(/\.(tsx?|json|js)$/, "")
    .replace(/\/index$/, "");
  return path.replace(/[^A-Za-z0-9]+/g, "-").replace(/^-|-$/g, "") || fallback;
}

/**
 * Builds every entry and returns the generated files, keyed by their path relative to
 * supabase/functions: `_vendor/**` and one `<function>/deno.json` per function.
 */
export async function renderEdgeFiles(): Promise<Map<string, string>> {
  const outDir = mkdtempSync(join(tmpdir(), "xos-edge-"));
  // The bundle is production code whatever the caller's mode (Vitest sets NODE_ENV=test).
  const previousNodeEnv = process.env["NODE_ENV"];
  process.env["NODE_ENV"] = "production";
  try {
    await build({
      configFile: false,
      mode: "production",
      logLevel: "silent",
      root: fileURLToPath(new URL(".", import.meta.url)),
      plugins: [
        {
          // The plan registry, parsed and validated now from packages/schemas/plans.yaml, embedded as
          // data: stripe-webhook needs neither yaml nor zod at run time, and a bad plans.yaml fails
          // the build instead of a cold start.
          name: "xos-edge-plan-registry",
          resolveId(id) {
            return id === PLAN_REGISTRY ? `\0${PLAN_REGISTRY}` : null;
          },
          load(id) {
            if (id !== `\0${PLAN_REGISTRY}`) return null;
            return `export const planRegistry = ${JSON.stringify(loadPlanRegistry())};\n`;
          },
        },
      ],
      build: {
        outDir,
        emptyOutDir: true,
        minify: false,
        sourcemap: false,
        target: "es2022",
        lib: {
          entry: Object.fromEntries(
            EDGE_ENTRIES.map((name) => [name, join(ENTRIES_DIR, `${name}.ts`)]),
          ),
          formats: ["es"],
          fileName: (_format, name) => `${name}.js`,
        },
        rollupOptions: {
          external: (id) =>
            id.startsWith("node:") ||
            EDGE_EXTERNALS.some((name) => id === name || id.startsWith(`${name}/`)),
          // An npm package is loaded only when the code that uses it is: an unused import of one
          // (a module included for another export) must not load it at boot.
          treeshake: { moduleSideEffects: "no-external" },
          output: {
            // Readable names across chunks (`notificationStore`, not `o`), for review and stack traces.
            minifyInternalExports: false,
            chunkFileNames: (chunk) =>
              `chunks/${chunkName(chunk.facadeModuleId ?? chunk.moduleIds.at(-1), chunk.name)}.js`,
          },
        },
      },
    });
    const files = new Map<string, string>();
    const options = (await resolveConfig(CATALOG_PATH)) ?? {};
    for (const file of listFiles(outDir)) {
      const target = join(VENDOR_DIR, file);
      const raw = readFileSync(join(outDir, file), "utf8");
      files.set(
        posixPath(relative(FUNCTIONS_DIR, target)),
        await format(`${STAMP}${raw}`, { ...options, filepath: target }),
      );
    }
    for (const [path, text] of importMaps(files)) {
      files.set(path, await format(text, { ...options, filepath: join(FUNCTIONS_DIR, path) }));
    }
    return files;
  } finally {
    if (previousNodeEnv === undefined) delete process.env["NODE_ENV"];
    else process.env["NODE_ENV"] = previousNodeEnv;
    rmSync(outDir, { recursive: true, force: true });
  }
}

function listFiles(root: string, prefix = ""): string[] {
  return readdirSync(join(root, prefix), { withFileTypes: true })
    .flatMap((entry) =>
      entry.isDirectory()
        ? listFiles(root, join(prefix, entry.name))
        : [posixPath(join(prefix, entry.name))],
    )
    .sort();
}

// Imports in the generated JavaScript and the functions' own TypeScript. Type-only imports are
// erased before Deno resolves anything, so they are skipped.
const STATIC_IMPORT =
  /^[ \t]*(?:import|export)\s+(?!type\b)(?:[^"';]*?\sfrom\s*)?["']([^"']+)["']/gm;
const DYNAMIC_IMPORT = /\bimport\(\s*["']([^"']+)["']/g;

export interface FunctionGraph {
  /** Files loaded when the function boots, relative to supabase/functions. */
  readonly boot: readonly string[];
  /** Files loaded only through a dynamic import, when a request needs them. */
  readonly lazy: readonly string[];
  /** npm packages (bare specifiers) imported at boot. */
  readonly bootPackages: readonly string[];
  /** npm packages imported only through a dynamic import. */
  readonly lazyPackages: readonly string[];
}

/**
 * The module graph of a function from its index.ts: its own sources, _shared and the vendored files
 * it reaches. `read` returns a file's text by its path relative to supabase/functions, or undefined.
 */
export function functionGraph(
  fn: string,
  read: (path: string) => string | undefined,
): FunctionGraph {
  const boot = new Set<string>();
  const lazy = new Set<string>();
  const bootPackages = new Set<string>();
  const lazyPackages = new Set<string>();
  const visit = (path: string, atBoot: boolean): void => {
    if (boot.has(path) || (!atBoot && lazy.has(path))) return;
    const text = read(path);
    if (text === undefined) throw new Error(`${fn} imports ${path}, which does not exist`);
    (atBoot ? boot : lazy).add(path);
    if (atBoot) lazy.delete(path);
    const follow = (specifier: string, staticImport: boolean) => {
      const now = atBoot && staticImport;
      if (specifier.startsWith("node:")) return;
      if (specifier.startsWith(".")) {
        visit(posix.normalize(posix.join(posix.dirname(path), specifier)), now);
        return;
      }
      (now ? bootPackages : lazyPackages).add(specifier);
    };
    for (const match of text.matchAll(STATIC_IMPORT)) follow(match[1] ?? "", true);
    for (const match of text.matchAll(DYNAMIC_IMPORT)) follow(match[1] ?? "", false);
  };
  visit(`${fn}/index.ts`, true);
  for (const name of bootPackages) lazyPackages.delete(name);
  return {
    boot: [...boot].sort(),
    lazy: [...lazy].sort(),
    bootPackages: [...bootPackages].sort(),
    lazyPackages: [...lazyPackages].sort(),
  };
}

interface DenoConfig {
  readonly compilerOptions?: Record<string, unknown>;
  readonly imports: Readonly<Record<string, string>>;
}

/** A file under supabase/functions as committed, or undefined when there is none. */
export function readEdgeFile(path: string): string | undefined {
  try {
    return readFileSync(join(FUNCTIONS_DIR, path), "utf8");
  } catch {
    return undefined;
  }
}

/** Reads a function source from disk, or a generated file from the build when there is one. */
function reader(generated: ReadonlyMap<string, string>) {
  return (path: string): string | undefined => {
    const built = generated.get(path);
    if (built !== undefined) return built;
    return path.startsWith("_vendor/") ? undefined : readEdgeFile(path);
  };
}

/** Each function's deno.json: the catalog's settings with only the packages its graph imports. */
function importMaps(generated: ReadonlyMap<string, string>): Map<string, string> {
  const catalog = JSON.parse(readFileSync(CATALOG_PATH, "utf8")) as DenoConfig;
  const read = reader(generated);
  const maps = new Map<string, string>();
  for (const fn of edgeFunctions()) {
    const graph = functionGraph(fn, read);
    const imports: Record<string, string> = {};
    for (const name of [...graph.bootPackages, ...graph.lazyPackages].sort()) {
      const pinned = catalog.imports[name];
      if (pinned === undefined) {
        throw new Error(`${fn} imports ${name}; pin it in supabase/functions/deno.json first`);
      }
      imports[name] = pinned;
    }
    const config: DenoConfig = { compilerOptions: catalog.compilerOptions ?? {}, imports };
    maps.set(`${fn}/deno.json`, `${JSON.stringify(config, null, 2)}\n`);
  }
  return maps;
}

/** The generated files committed now: everything in _vendor and each function's deno.json. */
export function committedEdgeFiles(): Map<string, string> {
  const files = new Map<string, string>();
  for (const file of listFiles(VENDOR_DIR)) {
    files.set(`_vendor/${file}`, readFileSync(join(VENDOR_DIR, file), "utf8"));
  }
  for (const fn of edgeFunctions()) {
    try {
      files.set(`${fn}/deno.json`, readFileSync(join(FUNCTIONS_DIR, fn, "deno.json"), "utf8"));
    } catch {
      // Missing: the comparison reports it.
    }
  }
  return files;
}

/** Paths that differ between two sets of generated files, as human-readable lines. */
export function differences(
  expected: ReadonlyMap<string, string>,
  actual: ReadonlyMap<string, string>,
): string[] {
  const lines: string[] = [];
  for (const [path, text] of expected) {
    const current = actual.get(path);
    if (current === undefined) lines.push(`missing  ${path}`);
    else if (current !== text) lines.push(`changed  ${path}`);
  }
  for (const path of actual.keys()) if (!expected.has(path)) lines.push(`extra    ${path}`);
  return lines.sort();
}

if (process.argv[1] !== undefined && fileURLToPath(import.meta.url) === process.argv[1]) {
  const files = await renderEdgeFiles();
  const stale = differences(files, committedEdgeFiles());
  if (process.argv.includes("--check")) {
    if (stale.length > 0) {
      console.error(
        `The Edge Function bundles are out of date. Run bundle:edge.\n${stale.join("\n")}`,
      );
      process.exit(1);
    }
    console.log("The Edge Function bundles match their sources.");
  } else {
    rmSync(VENDOR_DIR, { recursive: true, force: true });
    for (const [path, text] of files) {
      const target = join(FUNCTIONS_DIR, path);
      mkdirSync(dirname(target), { recursive: true });
      writeFileSync(target, text);
    }
    console.log(`Wrote ${files.size} files under supabase/functions (${stale.length} changed).`);
  }
}
