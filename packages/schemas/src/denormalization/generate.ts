import type { DenormalizationRegister } from "./model.ts";

/** Repository-relative path of the generated pgTAP fixture the catalog lints include. */
export const FIXTURE_PATH = "supabase/tests/1282_denormalization_register.psql";

/** Repository-relative path of the generated human view of the register. */
export const MARKDOWN_PATH = "docs/adr/denormalization-register.md";

const GENERATOR = "`pnpm --filter @xos/schemas generate:denormalization`";
const SOURCE = "docs/adr/denormalization-register.yaml";

function literal(value: string): string {
  return `'${value.replaceAll("'", "''")}'`;
}

function table(
  name: string,
  columns: readonly string[],
  key: string,
  rows: readonly (readonly string[])[],
) {
  const create = `create temporary table ${name} (${columns.map((c) => `${c} text not null`).join(", ")}, primary key (${key}));`;
  if (rows.length === 0) return [create];
  return [
    create,
    `insert into ${name} values`,
    rows.map((row) => `  (${row.map(literal).join(", ")})`).join(",\n") + ";",
  ];
}

/**
 * The SQL fixture `1282_normalization_lints.test.sql` and `0202_identity_core.test.sql` include: one temporary table
 * per allow-list. A pure function of the register, so the same YAML always yields the same file. The test's
 * transaction drops the tables.
 */
export function renderRegisterFixture(register: DenormalizationRegister): string {
  return [
    `-- Generated by ${GENERATOR} from ${SOURCE}.`,
    "-- Never edit by hand; on a merge conflict, take either side and rerun the generator. The catalog lints in",
    "-- 1282_normalization_lints.test.sql and the tenant column check in 0202_identity_core.test.sql read these tables,",
    "-- and the transaction they run in drops them.",
    ...table(
      "register_own_names",
      ["column_name"],
      "column_name",
      register.ownNames.map((e) => [e.name]),
    ),
    ...table(
      "register_json",
      ["column_name", "exception"],
      "column_name",
      register.json.map((e) => [e.column, e.kind]),
    ),
    ...table(
      "register_arrays",
      ["column_name", "kind"],
      "column_name",
      register.arrays.map((e) => [e.column, e.kind]),
    ),
    ...table(
      "register_restated",
      ["column_name", "parent_column", "kind"],
      "column_name, parent_column",
      register.restated.map((e) => [e.column, e.parent, e.kind]),
    ),
    ...table(
      "register_stored",
      ["column_name", "kind"],
      "column_name",
      register.stored.map((e) => [e.column, e.kind]),
    ),
    ...table(
      "register_tenant_exceptions",
      ["table_name", "kind"],
      "table_name",
      register.tenantExceptions.map((e) => [e.table, e.kind]),
    ),
    "",
  ].join("\n");
}

function cell(value: string): string {
  return value.replaceAll("|", "\\|").replaceAll("\n", " ");
}

function code(name: string): string {
  return `\`${name}\``;
}

function markdownTable(header: readonly string[], rows: readonly (readonly string[])[]): string[] {
  if (rows.length === 0) return ["None."];
  return [
    `| ${header.join(" | ")} |`,
    `| ${header.map(() => "---").join(" | ")} |`,
    ...rows.map((row) => `| ${row.map(cell).join(" | ")} |`),
  ];
}

function withFinding(note: string, finding: string | null): string {
  return finding === null ? note : `${note} ([${finding}](../../legal/qa/findings/${finding}.md))`;
}

/** The human view of the register, docs/adr/denormalization-register.md, before Prettier lays out its tables. */
export function renderRegisterMarkdown(register: DenormalizationRegister): string {
  return [
    "# Denormalization Register",
    "",
    `<!-- Generated by ${GENERATOR} from ${SOURCE}. Never edit by hand. -->`,
    "",
    `Section 3.15 allows a materialized view or stored derived value only for measured performance. Each one is listed here. The register's source is [\`denormalization-register.yaml\`](denormalization-register.yaml); this page is generated from it, and so is \`${FIXTURE_PATH}\`, the allow-lists the pgTAP catalog lints in \`supabase/tests/1282_normalization_lints.test.sql\` and the tenant column check in \`supabase/tests/0202_identity_core.test.sql\` read. A new json or jsonb column, array column, restated parent column, stored total or \`app\` table without the tenant columns fails those tests until it is reviewed and listed below (ADR 0068).`,
    "",
    "## Stored derived values and materialized views",
    "",
    ...markdownTable(
      ["Object", "Source", "Refresh rule", "Measured reason", "ADR"],
      register.derived.map((d) => [
        d.objects.map(code).join(", "),
        d.source,
        d.refresh,
        d.reason,
        d.adr,
      ]),
    ),
    "",
    "## JSON columns",
    "",
    "ADR 0002 allows JSON columns only for rich text documents, audit diffs and provider payloads. `registered` means the column is a derived entry above; `finding` means it is a violation with an open finding.",
    "",
    ...markdownTable(
      ["Column", "Exception", "Why"],
      register.json.map((e) => [code(e.column), e.kind, withFinding(e.note, e.finding)]),
    ),
    "",
    "## Array columns",
    "",
    "ADR 0002 forbids arrays of identifiers, and pgTAP 1280 refuses any `uuid[]` column. Each array column below holds a short closed set or a payload read whole, never a relationship.",
    "",
    ...markdownTable(
      ["Column", "Kind", "Why"],
      register.arrays.map((e) => [code(e.column), e.kind, withFinding(e.note, e.finding)]),
    ),
    "",
    "## Restated parent columns",
    "",
    "A column with the same name and type as a column of the table one of its foreign keys references, outside that table's primary key, restates that column unless a composite foreign key keeps the two equal. `registered` is a derived entry above; `fact` is kept as it was when written while the parent can change later; `own` is the row's own value, which can differ from the parent's or which the row needs without the link, because the link is optional.",
    "",
    ...markdownTable(
      ["Column", "Restates", "Kind", "Why"],
      register.restated.map((e) => [
        code(e.column),
        code(e.parent),
        e.kind,
        withFinding(e.note, e.finding),
      ]),
    ),
    "",
    "### Names the restated-column lint never compares",
    "",
    "These names describe the row itself wherever they appear. The lint never compares them and never follows a foreign key made only of them, so `org_id` and the ADR 0002 row stamps never pull in the organization or the person who wrote a row.",
    "",
    ...markdownTable(
      ["Name", "Why"],
      register.ownNames.map((e) => [code(e.name), e.note]),
    ),
    "",
    "## Stored values named like totals",
    "",
    "Columns named like a total, count, sum, balance, score, percent or readiness that are not generated columns. `fact` is fixed when something happened and later rows cannot reproduce it; `input` is set by a person, a provider or the canon.",
    "",
    ...markdownTable(
      ["Column", "Kind", "Why"],
      register.stored.map((e) => [code(e.column), e.kind, withFinding(e.note, e.finding)]),
    ),
    "",
    "## Tables without the tenant columns",
    "",
    "ADR 0002 puts `org_id` and the audit columns on every tenant table. The identity rows of Section 4.8.1 and platform tables belong to no org, and ADR 0019 item 10 keeps person-owned rows outside an org, which ADR 0033 decision 69 accepts as a stated exception.",
    "",
    ...markdownTable(
      ["Table", "Kind", "Why"],
      register.tenantExceptions.map((e) => [code(e.table), e.kind, e.note]),
    ),
    "",
  ].join("\n");
}
