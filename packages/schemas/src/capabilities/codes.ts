import { allCapabilities } from "./grants.ts";
import type { CapabilityRegistry } from "./model.ts";

/** Path of the generated capability code module, from the package root. */
export const CAPABILITY_CODES_MODULE = "src/capabilities/codes.generated.ts";

/**
 * The generated TypeScript module: every capability code as a const list and the `CapabilityCode`
 * union over it, so a capability check that names a code the registry lacks fails typecheck, and the
 * `xos/registered-capability` lint reads the same list (Section 3.15).
 */
export function renderCapabilityCodesModule(registry: CapabilityRegistry): string {
  const codes = allCapabilities(registry).map((c) => c.code);
  return [
    "// Generated by `pnpm --filter @xos/schemas generate:capabilities` from packages/schemas/capabilities.yaml.",
    "// Never edit by hand; on a merge conflict, take either side and rerun the generator.",
    "",
    "/** Every capability code in the registry, in registry order. */",
    `export const CAPABILITY_CODES = ${JSON.stringify(codes, null, 2)} as const;`,
    "",
    "/** A capability code the registry defines. */",
    "export type CapabilityCode = (typeof CAPABILITY_CODES)[number];",
    "",
  ].join("\n");
}
