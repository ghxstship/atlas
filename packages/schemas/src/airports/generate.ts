import type { Airport } from "./load.ts";

/** Repository-relative path of the generated airports seed migration. */
export const AIRPORTS_SEED_MIGRATION = "supabase/migrations/2652_airports_seed.sql";

const BATCH = 500;

function literal(value: string | null): string {
  return value === null ? "null" : `'${value.replaceAll("'", "''")}'`;
}

/**
 * The seed migration of app.airports: one idempotent upsert per batch of 500, so a newer snapshot updates names and
 * reactivates codes in place. Codes missing from a newer snapshot are left as they are; existing travel requests keep
 * their reference.
 */
export function renderAirportsSeed(airports: readonly Airport[]): string {
  const header = [
    "-- 2652_airports_seed.sql",
    "-- GENERATED by `pnpm --filter @xos/schemas generate:airports` from packages/schemas/airports/airports.csv. Do not edit.",
    "-- R5 Project facts (RRR-184, ADR 0102): the airports of app.airports (2651), by IATA code.",
    `-- ${airports.length} airports.`,
    "",
  ];
  const batches: string[] = [];
  for (let start = 0; start < airports.length; start += BATCH) {
    const rows = airports
      .slice(start, start + BATCH)
      .map(
        (a) =>
          `  (${literal(a.iataCode)}, ${literal(a.name)}, ${literal(a.municipality)}, ${literal(a.countryCode)})`,
      );
    batches.push(
      [
        "insert into app.airports (iata_code, name, municipality, country_code) values",
        `${rows.join(",\n")}`,
        "on conflict (iata_code) do update set name = excluded.name, municipality = excluded.municipality,",
        "  country_code = excluded.country_code, is_active = true;",
        "",
      ].join("\n"),
    );
  }
  return `${header.join("\n")}${batches.join("\n")}`;
}
