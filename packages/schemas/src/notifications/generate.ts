import type { NotificationKindRegistry } from "./model.ts";

/** Path of the generated registry module, from the package root. */
export const NOTIFICATION_REGISTRY_MODULE = "src/notifications/registry.generated.ts";

/**
 * The generated TypeScript module: the preference matrix (channel defaults and categories in display
 * order) and the templates index (every kind with its category, email template, push category and
 * catalog keys), for the apps and the senders, which cannot read files.
 */
export function renderNotificationRegistryModule(registry: NotificationKindRegistry): string {
  return [
    "// Generated by `pnpm --filter @xos/schemas generate:notifications` from packages/schemas/notification-kinds.yaml.",
    "// Never edit by hand; on a merge conflict, take either side and rerun the generator.",
    'import type { CategoryDefinition, ChannelDefinition, EmailTemplateDefinition, KindDefinition } from "./model.ts";',
    "",
    `export const NOTIFICATION_REGISTRY_VERSION = ${registry.version};`,
    "",
    "/** Channels with their default when nobody chose: the preference matrix columns. */",
    `export const NOTIFICATION_CHANNEL_DEFAULTS: readonly ChannelDefinition[] = ${JSON.stringify(registry.channels, null, 2)};`,
    "",
    "/** Preference categories in display order: the preference matrix rows. */",
    `export const NOTIFICATION_CATEGORIES: readonly CategoryDefinition[] = ${JSON.stringify(registry.categories, null, 2)};`,
    "",
    "/** React Email templates. */",
    `export const NOTIFICATION_EMAIL_TEMPLATES: readonly EmailTemplateDefinition[] = ${JSON.stringify(registry.emailTemplates, null, 2)};`,
    "",
    "/** The templates index: every notification kind. */",
    `export const NOTIFICATION_KINDS: readonly KindDefinition[] = ${JSON.stringify(registry.kinds, null, 2)};`,
    "",
  ].join("\n");
}
