/**
 * Code generation for the handler seam (ADR 0021, item 4).
 *
 * - `src/handlers/index.generated.ts` imports every module handler file in `MODULES` order, so
 *   module agents add handlers by editing only their own file.
 * - `src/catalog/modules/index.generated.ts` imports every module's additive operations the same
 *   way, so a module adds operations beyond the frozen catalog without a shared catalog edit.
 * - `src/contract/operations.generated.ts` turns the frozen OpenAPI document into TypeScript
 *   types: one entry per operation with its module, path parameters, query, body and success
 *   responses. Handlers are typed against it, so a handler cannot return a body the contract
 *   does not allow.
 *
 * All three files are deterministic and formatted with the repository Prettier config.
 */
import { existsSync, readFileSync, readdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";
import { MODULES } from "../catalog/types.ts";

export const HANDLERS_DIR = fileURLToPath(new URL("../handlers/", import.meta.url));
export const HANDLER_INDEX_FILE = fileURLToPath(
  new URL("../handlers/index.generated.ts", import.meta.url),
);
export const OPERATION_TYPES_FILE = fileURLToPath(
  new URL("../contract/operations.generated.ts", import.meta.url),
);
export const ADDITIONS_DIR = fileURLToPath(new URL("../catalog/modules/", import.meta.url));
export const ADDITIONS_INDEX_FILE = fileURLToPath(
  new URL("../catalog/modules/index.generated.ts", import.meta.url),
);
const DOCUMENT_FILE = fileURLToPath(new URL("../../openapi/v1.json", import.meta.url));

const BANNER =
  "// Generated by `pnpm --filter @xos/api generate:handlers`. Do not edit by hand; rerun the generator.";

/** The handler file name for a module: kebab-case of the tag. */
export function moduleFileName(module: string): string {
  return `${module.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase()}.ts`;
}

function camel(module: string): string {
  return module.charAt(0).toLowerCase() + module.slice(1);
}

async function prettify(source: string, file: string): Promise<string> {
  const config = (await resolveConfig(file)) ?? {};
  return format(source, { ...config, parser: "typescript" });
}

/** Module files present in `dir` (default `src/handlers`), validated against `MODULES`. */
export function handlerModules(dir: string = HANDLERS_DIR): string[] {
  const known = new Map(MODULES.map((m) => [moduleFileName(m), m as string]));
  const files = existsSync(dir)
    ? readdirSync(dir).filter((f) => f.endsWith(".ts") && f !== "index.generated.ts")
    : [];
  for (const file of files) {
    if (!known.has(file)) {
      throw new Error(
        `${dir}${file} does not name a module. Module files are ${[...known.keys()].join(", ")}.`,
      );
    }
  }
  const present = new Set(files);
  return MODULES.filter((m) => present.has(moduleFileName(m)));
}

interface IndexSpec {
  readonly dir: string;
  readonly file: string;
  readonly symbol: string;
  readonly type: string;
  readonly typeModule: string;
  readonly constant: string;
  readonly doc: string;
}

async function renderIndex(spec: IndexSpec): Promise<string> {
  const modules = handlerModules(spec.dir);
  const imports = modules
    .map((m) => `import { ${spec.symbol} as ${camel(m)} } from "./${moduleFileName(m)}";`)
    .join("\n");
  const source = `${BANNER}
/** ${spec.doc} */
import type { ${spec.type} } from "${spec.typeModule}";
${imports}

export const ${spec.constant}: readonly ${spec.type}[] = [${modules.map(camel).join(", ")}];
`;
  return prettify(source, spec.file);
}

export function renderHandlerIndex(dir: string = HANDLERS_DIR): Promise<string> {
  return renderIndex({
    dir,
    file: HANDLER_INDEX_FILE,
    symbol: "handlers",
    type: "AnyModuleHandlers",
    typeModule: "../runtime/handler.ts",
    constant: "MODULE_HANDLERS",
    doc: "Every module's handler set, in catalog `MODULES` order.",
  });
}

export function renderAdditionsIndex(dir: string = ADDITIONS_DIR): Promise<string> {
  return renderIndex({
    dir,
    file: ADDITIONS_INDEX_FILE,
    symbol: "additions",
    type: "ModuleAdditions",
    typeModule: "../additions.ts",
    constant: "MODULE_ADDITIONS",
    doc: "Every module's additive operations, in catalog `MODULES` order.",
  });
}

type Json = Record<string, unknown>;

const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

function key(name: string): string {
  return IDENTIFIER.test(name) ? name : JSON.stringify(name);
}

function refName(ref: string): string {
  const parts = ref.split("/");
  return parts[parts.length - 1] as string;
}

/** JSON Schema (OpenAPI 3.1 dialect, as emitted by zod) to a TypeScript type expression. */
export function schemaType(schema: unknown): string {
  if (schema === true || schema === undefined) return "unknown";
  if (schema === false) return "never";
  const s = schema as Json;
  if (typeof s["$ref"] === "string") return `Components[${JSON.stringify(refName(s["$ref"]))}]`;
  if (Array.isArray(s["anyOf"])) return union(s["anyOf"].map(schemaType));
  if (Array.isArray(s["oneOf"])) return union(s["oneOf"].map(schemaType));
  if (Array.isArray(s["allOf"])) {
    const parts = s["allOf"].map(schemaType);
    return parts.length === 1 ? (parts[0] as string) : parts.map((p) => `(${p})`).join(" & ");
  }
  if ("const" in s) return JSON.stringify(s["const"]);
  if (Array.isArray(s["enum"])) return union(s["enum"].map((v) => JSON.stringify(v)));
  const type = s["type"];
  if (Array.isArray(type)) return union(type.map((t) => schemaType({ ...s, type: t })));
  switch (type) {
    case "string":
      return "string";
    case "integer":
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "null":
      return "null";
    case "array": {
      if (Array.isArray(s["prefixItems"]))
        return `[${s["prefixItems"].map(schemaType).join(", ")}]`;
      return `Array<${schemaType(s["items"])}>`;
    }
    case "object":
      return objectType(s);
    default:
      if (s["properties"] !== undefined) return objectType(s);
      return "unknown";
  }
}

function union(parts: string[]): string {
  const unique = [...new Set(parts)];
  if (unique.length === 0) return "never";
  return unique.length === 1 ? (unique[0] as string) : unique.map((p) => `(${p})`).join(" | ");
}

function objectType(s: Json): string {
  const properties = (s["properties"] ?? {}) as Record<string, unknown>;
  const required = new Set((s["required"] ?? []) as string[]);
  const members = Object.entries(properties).map(
    ([name, value]) => `${key(name)}${required.has(name) ? "" : "?"}: ${schemaType(value)};`,
  );
  const extra = s["additionalProperties"];
  if (extra !== undefined && extra !== false) {
    const value = extra === true ? "unknown" : schemaType(extra);
    if (members.length === 0) return `Record<string, ${value}>`;
    members.push(`[key: string]: unknown;`);
  }
  if (members.length === 0)
    return extra === false ? "Record<string, never>" : "Record<string, unknown>";
  return `{ ${members.join(" ")} }`;
}

interface Parameter {
  readonly name: string;
  readonly in: string;
  readonly required?: boolean;
  readonly schema?: unknown;
}

const METHODS = ["get", "post", "put", "patch", "delete"] as const;

/** Operation types from the document text (default: the committed `openapi/v1.json`). */
export async function renderOperationTypes(
  documentText: string = readFileSync(DOCUMENT_FILE, "utf8"),
): Promise<string> {
  const doc = JSON.parse(documentText) as {
    paths: Record<string, Record<string, Json>>;
    components: { schemas: Record<string, unknown>; parameters: Record<string, Parameter> };
  };
  const resolveParameter = (p: Json): Parameter => {
    const ref = p["$ref"];
    if (typeof ref !== "string") return p as unknown as Parameter;
    const target = doc.components.parameters[refName(ref)];
    if (target === undefined) throw new Error(`Unresolved parameter ${ref}.`);
    return target;
  };

  const components = Object.keys(doc.components.schemas)
    .sort()
    .map((name) => `  ${key(name)}: ${schemaType(doc.components.schemas[name])};`);

  const operations: string[] = [];
  const byModule = new Map<string, string[]>(MODULES.map((m) => [m, []]));
  for (const [path, item] of Object.entries(doc.paths)) {
    for (const method of METHODS) {
      const op = item[method] as Json | undefined;
      if (op === undefined) continue;
      const id = op["operationId"] as string;
      const module = (op["tags"] as string[])[0] as string;
      const list = byModule.get(module);
      if (list === undefined) throw new Error(`${id} is tagged ${module}, which is not a module.`);
      list.push(id);
      const parameters = ((op["parameters"] ?? []) as Json[]).map(resolveParameter);
      const group = (where: string) => {
        const ps = parameters.filter((p) => p.in === where);
        if (ps.length === 0) return "Record<string, never>";
        return `{ ${ps
          .map((p) => `${key(p.name)}${p.required === true ? "" : "?"}: ${schemaType(p.schema)};`)
          .join(" ")} }`;
      };
      const body = (op["requestBody"] as Json | undefined)?.["content"] as
        Record<string, Json> | undefined;
      const bodyType =
        body?.["application/json"] === undefined
          ? "undefined"
          : schemaType(body["application/json"]["schema"]);
      const responses = Object.entries(op["responses"] as Record<string, Json>)
        .filter(([status]) => /^2\d\d$/.test(status))
        .map(([status, response]) => {
          const content = response["content"] as Record<string, Json> | undefined;
          const schema = content?.["application/json"]?.["schema"];
          return `${status}: ${schema === undefined ? "null" : schemaType(schema)};`;
        });
      operations.push(`  ${JSON.stringify(id)}: {
    module: ${JSON.stringify(module)};
    method: ${JSON.stringify(method)};
    path: ${JSON.stringify(path)};
    params: ${group("path")};
    query: ${group("query")};
    body: ${bodyType};
    responses: { ${responses.join(" ")} };
  };`);
    }
  }

  const moduleMap = [...byModule.entries()]
    .map(
      ([m, ids]) =>
        `  ${m}: ${ids.length === 0 ? "never" : union(ids.map((i) => JSON.stringify(i)))};`,
    )
    .join("\n");

  const source = `${BANNER}
/**
 * TypeScript types for every operation in \`openapi/v1.json\`. Handlers are typed against these,
 * so request and response shapes always match the published contract.
 */

/** Component schemas of the contract, by component name. */
export interface Components {
${components.join("\n")}
}

/** Every operation, keyed by operationId. */
export interface Operations {
${operations.join("\n")}
}

/** The operationIds of each module. */
export interface ModuleOperations {
${moduleMap}
}
`;
  return prettify(source, OPERATION_TYPES_FILE);
}
