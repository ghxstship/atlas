/**
 * Writes one Storybook story per design preview (RRR-34, design handoff build step 7) into
 * stories/generated/. Each preview in design/xos-design-system/components/<Name>/preview.html renders
 * the reference component with representative props through `XOS.<Name>`; the story runs the same
 * code against the production @xos/ui exports, which the contract test holds to the reference props.
 * Previews without a script (Cover) and previews that draw with reference-only CSS (ControlStates)
 * have hand-written stories in stories/.
 *
 * Usage: node scripts/generate-stories.mjs [--check]
 * With --check, writes nothing and exits 1 when a generated story is missing, stale or extra.
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import * as prettier from "prettier";

const here = dirname(fileURLToPath(import.meta.url));
const source = join(here, "../../../design/xos-design-system/components");
const target = join(here, "../stories/generated");
const HAND_WRITTEN = new Set(["Cover", "ControlStates"]);

function story(name, html) {
  const card = /@dsCard(?:\s+group="([^"]+)")?(?:\s+height=(\d+))?/.exec(html);
  const group = card?.[1] ?? "Foundations";
  const height = Number(card?.[2] ?? 240);
  const script = /<script>([\s\S]*?)<\/script>/.exec(html)?.[1];
  if (!script) return null;
  const body = script
    .replace(/^\s*var X = window\.XOS, h = React\.createElement;\s*$/m, "")
    .replace(/ReactDOM\.createRoot\(document\.getElementById\('root'\)\)\.render\(/, "return (");
  return `/* Generated by scripts/generate-stories.mjs from design/xos-design-system/components/${name}/preview.html. Do not edit; run \`pnpm --filter @xos/ui generate:stories\`. */
import { createElement } from "react";
import * as X from "../../src/index.ts";

const h = createElement;
const React = { createElement };

export default {
  title: ${JSON.stringify(`${group}/${name}`)},
  parameters: { preview: { height: ${height} } },
};

export const Preview = {
  name: ${JSON.stringify(name)},
  render: () => {
    void React;
    void X;
    void h;
${body}
  },
};
`;
}

const outputs = new Map();
for (const name of readdirSync(source).sort()) {
  const file = join(source, name, "preview.html");
  if (HAND_WRITTEN.has(name) || !existsSync(file)) continue;
  const code = story(name, readFileSync(file, "utf8"));
  if (!code) continue;
  const path = join(target, `${name}.stories.js`);
  const config = (await prettier.resolveConfig(path)) ?? {};
  outputs.set(`${name}.stories.js`, await prettier.format(code, { ...config, filepath: path }));
}

if (process.argv.includes("--check")) {
  const present = existsSync(target) ? readdirSync(target) : [];
  const problems = [
    ...[...outputs]
      .filter(([f, c]) => !present.includes(f) || readFileSync(join(target, f), "utf8") !== c)
      .map(([f]) => f),
    ...present.filter((f) => !outputs.has(f)),
  ];
  if (problems.length) {
    console.error(
      `stories/generated is out of date (${problems.join(", ")}). Run pnpm --filter @xos/ui generate:stories.`,
    );
    process.exit(1);
  }
} else {
  rmSync(target, { recursive: true, force: true });
  mkdirSync(target, { recursive: true });
  for (const [file, code] of outputs) writeFileSync(join(target, file), code);
  console.log(`Wrote ${outputs.size} stories to stories/generated`);
}
