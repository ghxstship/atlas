import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";

/**
 * Generates src/database.types.ts from the local Supabase database (Section 3.15: data shapes come
 * from the migrations). Runs `supabase gen types typescript --local` for the schemas the apps read,
 * stamps the file, and formats it with the repository Prettier config so format:check stays green.
 * With --check, writes nothing and exits 1 when the committed file differs (gate 12 drift check).
 * Needs a running local stack with every migration applied (`supabase db start` or `db reset`).
 */
const SCHEMAS = ["app", "xpms"] as const;
const repoRoot = fileURLToPath(new URL("../../../", import.meta.url));
const target = fileURLToPath(new URL("../src/database.types.ts", import.meta.url));
const STAMP = [
  "// Generated by `pnpm --filter @xos/data types:generate` from the local Supabase database.",
  "// Source of truth: supabase/migrations. Never edit by hand; CI regenerates and diffs it.",
  "",
].join("\n");

const raw = execFileSync(
  "supabase",
  ["gen", "types", "typescript", "--local", ...SCHEMAS.flatMap((s) => ["--schema", s])],
  { cwd: repoRoot, encoding: "utf8", stdio: ["ignore", "pipe", "inherit"], maxBuffer: 64 << 20 },
);
const options = (await resolveConfig(target)) ?? {};
const generated = await format(`${STAMP}${raw}`, { ...options, filepath: target });

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch (error) {
    console.error(`Cannot read ${target}: ${String(error)}`);
    process.exit(1);
  }
  if (current !== generated) {
    console.error("packages/data/src/database.types.ts is out of date. Run types:generate.");
    process.exit(1);
  }
  console.log("database.types.ts matches the local database.");
} else {
  writeFileSync(target, generated);
  console.log("Wrote packages/data/src/database.types.ts.");
}
