import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

/**
 * Writes src/documents/fonts.generated.ts from @fontsource/inter (SIL OFL 1.1): the Latin subset
 * of Inter Regular and SemiBold (WOFF 1.0; fontkit 2.0.4 cannot subset composite glyphs from WOFF2) as hex text. Generated documents embed these fonts (PDF/UA-1
 * requires every font embedded), and shipping them as module text means no runtime file read, so
 * the renderer works the same in a Next.js route, a test and the veraPDF check (ADR 0031).
 * Hex, not base64, so the finish guard (gate 2) can never match a word inside the data.
 * With --check, writes nothing and exits 1 when the generated file is out of date.
 */
const require = createRequire(import.meta.url);
const target = fileURLToPath(new URL("../src/documents/fonts.generated.ts", import.meta.url));
const fontPackage = require("@fontsource/inter/package.json") as { version: string };

const read = (weight: 400 | 600) =>
  readFileSync(require.resolve(`@fontsource/inter/files/inter-latin-${weight}-normal.woff`));

const generated = [
  `// Generated by \`pnpm --filter @xos/data documents:fonts\` from @fontsource/inter ${fontPackage.version}.`,
  "// Inter is licensed under the SIL Open Font License 1.1 (github.com/rsms/inter). Never edit by hand.",
  "",
  "/** Inter Regular, Latin subset, WOFF as hex. */",
  `export const INTER_REGULAR_HEX =\n  "${read(400).toString("hex")}";`,
  "",
  "/** Inter SemiBold, Latin subset, WOFF as hex. */",
  `export const INTER_SEMIBOLD_HEX =\n  "${read(600).toString("hex")}";`,
  "",
].join("\n");

if (process.argv.includes("--check")) {
  const current = readFileSync(target, "utf8");
  if (current !== generated) {
    console.error("src/documents/fonts.generated.ts is out of date. Run documents:fonts.");
    process.exit(1);
  }
  console.log("Document fonts are current.");
} else {
  writeFileSync(target, generated);
  console.log("Wrote src/documents/fonts.generated.ts.");
}
