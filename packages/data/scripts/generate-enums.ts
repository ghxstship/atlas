import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";
import { Constants } from "../src/database.types.ts";

/**
 * Writes src/enums.generated.ts from the Constants of src/database.types.ts: one named export per
 * database enum (`exportFormat` for app.export_format, `xpmsRefusal` for xpms.refusal). Client
 * components import these, because a bundler keeps only the lists a module names, where importing
 * Constants ships every enum to the browser (Section 3.15, rule 3; ADR 0123).
 * types:generate runs this after it rewrites database.types.ts. With --check, writes nothing and exits
 * 1 when the generated file is out of date.
 */
const target = fileURLToPath(new URL("../src/enums.generated.ts", import.meta.url));

function exportName(schema: string, name: string): string {
  const camel = name.replace(/_([a-z0-9])/g, (_, c: string) => c.toUpperCase());
  return schema === "app" ? camel : `${schema}${camel.charAt(0).toUpperCase()}${camel.slice(1)}`;
}

const lines = [
  "// Generated by `pnpm --filter @xos/data enums:generate` from src/database.types.ts. Never edit by hand.",
  "",
];
for (const [schema, { Enums }] of Object.entries(Constants)) {
  for (const [name, values] of Object.entries(Enums as Record<string, readonly string[]>)) {
    lines.push(`/** ${schema}.${name} */`);
    lines.push(`export const ${exportName(schema, name)} = ${JSON.stringify(values)} as const;`);
  }
}
const options = (await resolveConfig(target)) ?? {};
const generated = await format(`${lines.join("\n")}\n`, { ...options, filepath: target });

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch (error) {
    console.error(`Cannot read ${target}: ${String(error)}`);
    process.exit(1);
  }
  if (current !== generated) {
    console.error("src/enums.generated.ts is out of date. Run enums:generate.");
    process.exit(1);
  }
  console.log("enums.generated.ts matches database.types.ts.");
} else {
  writeFileSync(target, generated);
  console.log("Wrote src/enums.generated.ts.");
}
